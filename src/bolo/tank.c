/*********************************************************
*NAME:          tankStopCarryingPill
*AUTHOR:        John Morrison
*CREATION DATE: 21/6/00
*LAST MODIFIED: 21/6/00
*PURPOSE:
* Someone else has picked up a pill. We should check that
* we aren't carrying it ourselves and if so drop it (The
* server said so) because this can lead to desync problems
*
*ARGUMENTS:
*  value   - Pointer to the tank structure
*  pillNum - Pillbox number to drop if we are holding it
*********************************************************/
void tankStopCarryingPill(tank *value, BYTE pillNum) {
	bool done;        /* Have we done looping */
	tankCarryPb q;    /* temp pointer */
	tankCarryPb prev; /* temp pointer */

	done = FALSE;
	pillNum++;
	if (*value != NULL) {
		if (!IsEmpty((*value)->carryPills)) {
			prev = NULL;
			q = (*value)->carryPills;
			while (NonEmpty(q) && done == FALSE) {
				if (q->pillNum == pillNum) {
					/* We are carrying it */
					done = TRUE;
					if (prev == NULL) {
						(*value)->carryPills = q->next;
					} else {
						prev->next = q->next;
					}
					Dispose(q);
				} else {
					prev = q;
					q = q->next;
				}
			}
		}
	}
}

/*********************************************************
*NAME:          tankLayMine
*AUTHOR:        John Morrison
*CREATION DATE: 21/1/99
*LAST MODIFIED: 19/1/00
*PURPOSE:
* Tank has been requested to lay a mine
*
*ARGUMENTS:
*  value - Pointer to the tank structure
*  mp    - Pointer to the map strructure
*  pb    - Pointer to the pillboxes structure
*  bs    - Pointer to the bases structure
*********************************************************/
void tankLayMine(GameSim *sim, tank *value) {
  map *mp = &sim->mp;
  pillboxes *pb = &sim->pb;
  bases *bs = &sim->bs;
  bool isServer = sim->isServer;
  WORLD conv;   /* Used in the W->M conversion */
  BYTE bmx;     /* Tank X and Y Co-ordintes */
  BYTE bmy;
  BYTE terrain; /* The current terrain */

  conv = (*value)->x;
  conv >>= TANK_SHIFT_MAPSIZE;
  bmx = (BYTE) conv;
  conv = (*value)->y;
  conv >>= TANK_SHIFT_MAPSIZE;
  bmy = (BYTE) conv;

  if (mapIsMine(mp, bmx, bmy) == FALSE) {
    terrain = mapGetPos(mp, bmx, bmy);

    if (terrain != BUILDING && terrain != HALFBUILDING && terrain != BOAT && terrain != RIVER && terrain < MINE_START && (*value)->mines > 0 && (*value)->onBoat == FALSE && pillsExistPos(pb, bmx, bmy) == FALSE && basesExistPos(bs, bmx, bmy) == FALSE && !(*value)->destroyed) {
      (*value)->mines--;
      mapSetPos(sim, mp, bmx, bmy, (BYTE) (terrain + MINE_SUBTRACT), FALSE, FALSE);
      /* Record the layer so a later detonation credits its owner (mirrors the
       * LGM mine-lay path). minesSetOwner is unconditional; recordPlayerAction
       * is server-only (NULL on the client). */
      BYTE pn = gameSimGetTankPlayer(sim, value);
      minesSetOwner(&sim->mns, bmx, bmy, pn);
      if (sim->callbacks.recordPlayerAction) {
        sim->callbacks.recordPlayerAction(sim->callbacks.ctx, pn, PLAYER_ACTION_MINE, bmx, bmy);
      }
      if (isServer && sim->hiddenMines) {
        sim->callbacks.mineVisible(sim->callbacks.ctx, bmx, bmy, pn | 0x80);
      }
      if (isServer && sim->callbacks.mineLaid) {
        sim->callbacks.mineLaid(sim->callbacks.ctx, pn, bmx, bmy);
      }
      sim->callbacks.soundDist(sim->callbacks.ctx, manLayingMineNear, bmx, bmy);
      if (!(*value)->destroyed) {
        if (!isServer) {
          frontEndUpdateTankStatusBars(clientSimFromSim(sim), (*value)->shells, (*value)->mines, (*value)->armour, (*value)->trees);
        }
      } else {
        if (!isServer) {
          frontEndUpdateTankStatusBars(clientSimFromSim(sim), (*value)->shells, (*value)->mines, 0, (*value)->trees);
        }
      }
      if (!isServer) { clientSimRecalc((struct ClientSim *)sim); }
    }
  }
}

/*********************************************************
*NAME:          tankMineDamage
*AUTHOR:        John Morrison
*CREATION DATE: 21/1/99
*LAST MODIFIED: 20/6/00
*PURPOSE:
* A mine has exploded. Check to see if it has hurt the
* tank
*
*ARGUMENTS:
*  value - Pointer to the tank structure
*  mp    - Pointer to the map structure
*  pb    - Pointer to the pillboxes structure
*  bs    - Pointer to the bases structure
*  mx    - Map X Co-ordinate
*  my    - Map Y Co-ordinate
*********************************************************/
void tankMineDamage(GameSim *sim, tank *value, BYTE mx, BYTE my, BYTE owner) {
  bool isServer = sim->isServer;
  WORLD mineX; /* Mine X and Y World Co-ords */
  WORLD mineY;
  WORLD diffY; /* Difference beteween tank and mine */
  WORLD diffX;

  mineX =(mx << TANK_SHIFT_MAPSIZE) + MAP_SQUARE_MIDDLE;
  mineY =(my << TANK_SHIFT_MAPSIZE) + MAP_SQUARE_MIDDLE;

  if ((*value)->x > mineX) {
    diffX = (*value)->x - mineX;
  } else {
    diffX = mineX - (*value)->x;
  }

  if ((*value)->y > mineY) {
    diffY = (*value)->y - mineY;
  } else {
    diffY = mineY - (*value)->y;
  }


  /* Mac Bolo: less than one map square from the mine centre on each axis. */
  if (diffX < sim->rules.mine_damage_range &&
      diffY < sim->rules.mine_damage_range && !(*value)->destroyed) {
    BYTE armourBefore = (*value)->armour;
    BYTE amount = tankDamageAmount(sim, (BYTE) sim->rules.mine_damage, owner, gameSimGetTankPlayer(sim, value), LAST_DEATH_BY_MINES);
    /* Mac Bolo: three hits unless fatal, then two (which may still kill).
     * Apply this after modifiers, rounding up to preserve nonzero damage.
     * Exactly emptying the armour is survivable, hence the strict check. */
    if (amount > armourBefore) {
      amount -= (BYTE) (amount / sim->rules.mine_fatal_divisor);
    }
    bool wasDestroyed = tankApplyDamage(sim, value, amount, owner, LAST_DEATH_BY_MINES);
    if (sim->callbacks.recordDamage && owner != gameSimGetTankPlayer(sim, value)) {
      uint16_t eff = (armourBefore >= amount) ? amount : armourBefore;
      sim->callbacks.recordDamage(sim->callbacks.ctx, owner, DMG_TARGET_TANK,
                                  gameSimGetTankPlayer(sim, value), DMG_SRC_MINE, eff, false,
                                  (BYTE)((*value)->x >> TANK_SHIFT_MAPSIZE),
                                  (BYTE)((*value)->y >> TANK_SHIFT_MAPSIZE));
    }
    if (wasDestroyed) {
      BYTE dyingPlayer = gameSimGetTankPlayer(sim, value);
      (*value)->pendingDeathCause = DEATH_CAUSE_MINE;
      if (((*value)->shells + (*value)->mines) > sim->rules.big_explosion_threshold) {
        tkExplosionAddItem(sim, (*value)->x, (*value)->y, (TURNTYPE) ((*value)->angle), (BYTE) ((*value)->speed), (BYTE) TH_KILL_BIG, dyingPlayer);
      } else {
        tkExplosionAddItem(sim, (*value)->x, (*value)->y, (TURNTYPE) ((*value)->angle), (BYTE) ((*value)->speed), (BYTE) TH_KILL_SMALL, dyingPlayer);
      }
      (*value)->deathWait = (uint16_t) sim->rules.tank_death_ticks;
      /* owner is the slot that laid the mine, or NEUTRAL for a mine that came
       * with the map or whose layer has left (minesClearOwner releases their
       * cells). A tank that drives onto its own mine names itself, the shape
       * the drown arm uses for a death with no other player in it. Fired
       * before the pills go, so the count is what the tank still held. */
      sim->callbacks.tankKill(sim->callbacks.ctx, owner, dyingPlayer, LAST_DEATH_BY_MINES, tankGetNumCarriedPills(value));
      tankDropPills(sim, value);
    }
    if ((*value)->onBoat == TRUE) {
      (*value)->onBoat = FALSE;
      (*value)->boatState = BoatState_NotOnBoat;
      (*value)->speed = 0;
    }
    if (!isServer) {
      frontEndUpdateTankStatusBars(clientSimFromSim(sim), (*value)->shells, (*value)->mines, (*value)->armour, (*value)->trees);
    }

    if (!isServer) { clientSimRecalc((struct ClientSim *)sim); }
  }
}

/*********************************************************
*NAME:          tankNearMines
*PURPOSE:
*  Sweep for hidden mines in the current cell and 3
*  forward cells based on tank facing direction.
*
*ARGUMENTS:
*  sim   - Game simulation
*  mx    - Map X Co-ordinate
*  my    - Map Y Co-ordinate
*  dir   - Tank facing direction (0-15)
*********************************************************/
void tankNearMines(GameSim *sim, BYTE mx, BYTE my, BYTE dir) {
  map *mp = &sim->mp;
  bool needRecalc = FALSE;

  /* 3 forward cells for each of the 16 directions.
   * For each direction, the 3 neighbors whose angles are
   * closest to the facing direction are selected. */
  static const int8_t forwardDX[16][3] = {
    /*  0 N   */ { 0, -1,  1},
    /*  1 NNE */ { 0,  1,  1},
    /*  2 NE  */ { 1,  0,  1},
    /*  3 ENE */ { 1,  1,  0},
    /*  4 E   */ { 1,  1,  1},
    /*  5 ESE */ { 1,  1,  0},
    /*  6 SE  */ { 1,  1,  0},
    /*  7 SSE */ { 1,  0,  1},
    /*  8 S   */ { 0,  1, -1},
    /*  9 SSW */ { 0, -1, -1},
    /* 10 SW  */ {-1,  0, -1},
    /* 11 WSW */ {-1, -1,  0},
    /* 12 W   */ {-1, -1, -1},
    /* 13 WNW */ {-1, -1,  0},
    /* 14 NW  */ {-1, -1,  0},
    /* 15 NNW */ {-1,  0, -1},
  };
  static const int8_t forwardDY[16][3] = {
    /*  0 N   */ {-1, -1, -1},
    /*  1 NNE */ {-1, -1,  0},
    /*  2 NE  */ {-1, -1,  0},
    /*  3 ENE */ {-1,  0, -1},
    /*  4 E   */ { 0, -1,  1},
    /*  5 ESE */ { 0,  1,  1},
    /*  6 SE  */ { 1,  0,  1},
    /*  7 SSE */ { 1,  1,  0},
    /*  8 S   */ { 1,  1,  1},
    /*  9 SSW */ { 1,  1,  0},
    /* 10 SW  */ { 1,  1,  0},
    /* 11 WSW */ { 1,  0,  1},
    /* 12 W   */ { 0,  1, -1},
    /* 13 WNW */ { 0, -1, -1},
    /* 14 NW  */ {-1,  0, -1},
    /* 15 NNW */ {-1, -1,  0},
  };

  /* Check current cell */
  if (mapIsMine(mp, mx, my) == TRUE) {
    if (minesAddItem(&sim->mns, mx, my) == FALSE) {
      needRecalc = TRUE;
    }
  }

  /* Check 3 forward cells */
  BYTE d = dir & 0x0F;
  for (int i = 0; i < 3; i++) {
    BYTE fx = (BYTE)(mx + forwardDX[d][i]);
    BYTE fy = (BYTE)(my + forwardDY[d][i]);
    if (mapIsMine(mp, fx, fy) == TRUE) {
      if (minesAddItem(&sim->mns, fx, fy) == FALSE) {
        needRecalc = TRUE;
      }
    }
  }

  if (needRecalc == TRUE && !sim->isServer) {
    clientSimRecalc((struct ClientSim *)sim);
  }
}

