/*********************************************************
 * tankMoveUnified - Unified tank movement for both boat
 * and land, using iterative nudge collision model.
 * Replaces tankMoveOnBoat() and tankMoveOnLand().
 *********************************************************/
static void tankMoveUnified(GameSim *sim, tank *value, BYTE bmx, BYTE bmy,
                            tankButton tb, bool inBrain) {
  map *mp = &sim->mp;
  pillboxes *pb = &sim->pb;
  bases *bs = &sim->bs;
  bool isServer = sim->isServer;
  int xAmount = 0;
  int yAmount = 0;
  BYTE ang;
  BYTE newbmx;
  BYTE newbmy;
  bool movedThisTick = FALSE;

  /* Shared setup */
  tankCheckGroundClear(sim, value);
  tankTurn(sim, value, bmx, bmy, tb);
  tankAccel(sim, value, bmx, bmy, tb);

  /* Auto-slowdown */
  if ((*value)->speed > 0 && (*value)->autoSlowdown == TRUE && inBrain == FALSE) {
    if (tb != TDECEL && tb != TLEFTDECEL && tb != TRIGHTDECEL && tb != TACCEL && tb != TLEFTACCEL && tb != TRIGHTACCEL) {
      /* The same rate family as the decel keys, so the accel modifier
         governs it too. */
      (*value)->speed -= sim->rules.tank_autoslow_rate * tankModPct((*value)->mods.accel) / 100;
      if ((*value)->speed < 0) {
        (*value)->speed = 0;
      }
    }
  }

  ang = utilGet16Dir((*value)->angle);

  /* Step 1 — Tank-to-tank nudge */
  if (!sim->isPredicting) {
    WORLD preNudgeX = (*value)->x;
    WORLD preNudgeY = (*value)->y;
    tankNudgeOtherTanks(sim, value);
    if ((*value)->x != preNudgeX || (*value)->y != preNudgeY) {
      (*value)->obstructed = TRUE;
    }
  }

  /* Step 2 — Velocity movement with residual speed accumulation */
  (*value)->residualSpeed += (BYTE)(*value)->speed;
  if ((*value)->residualSpeed >= sim->rules.tank_min_move) {
    utilCalcDistance(&xAmount, &yAmount, (TURNTYPE)ang, (int)(*value)->residualSpeed);
    (*value)->x += xAmount;
    (*value)->y += yAmount;
    movedThisTick = TRUE;
    (*value)->residualSpeed = 0;
  }

  /* Step 3 — Step and decay together at the configured interval. The
   * default is every other 50 Hz update (40 ms), matching the Mac logs.
   * Ordinary driving still runs every update. A per-tank wait also works
   * during input replay/catch-up, independently of the server's clock. */
  if ((*value)->bumpWait > 0) {
    (*value)->bumpWait--;
  } else if ((*value)->bumpX != 0 || (*value)->bumpY != 0) {
    /* tankObj is packed; use aligned locals for the in/out arguments. */
    int32_t bumpX = (*value)->bumpX;
    int32_t bumpY = (*value)->bumpY;
    (*value)->x += tankStepKnockback(&bumpX, sim->rules.tank_bump_decay_shift);
    (*value)->y += tankStepKnockback(&bumpY, sim->rules.tank_bump_decay_shift);
    (*value)->bumpX = bumpX;
    (*value)->bumpY = bumpY;
    (*value)->bumpWait = (BYTE)(sim->rules.tank_bump_interval - 1);
  }

  /* Step 4 — Building nudge */
#ifndef BOLO_LEGACY_SQUARE_COLLISION
  /* Circle mode (default): after resolving the penetration, REDIRECT the
   * movement the wall blocked along the wall tangent, so the tank keeps
   * (near) full speed sliding past walls and corners — slippery wall physics.
   * The legacy grid-snap nudge + collision slowdown (Step 5) are bypassed in
   * this mode. */
  {
    WORLD oldX = (*value)->x & TANK_GRID_MASK;
    WORLD oldY = (*value)->y & TANK_GRID_MASK;
    int preX = (int)(*value)->x, preY = (int)(*value)->y;
    BumpInfo bumptype = tankNudgeBuildings(sim, value, (int) sim->rules.tank_nudge_iterations);
    int pushX = (int)(*value)->x - preX, pushY = (int)(*value)->y - preY;
    if ((pushX || pushY) && (xAmount || yAmount)) {
      const float SLIP = sim->rules.tank_wall_glide; /* 0 = plain slide, 1 = frictionless */
      float nlen = sqrtf((float)(pushX * pushX + pushY * pushY));
      float nx = pushX / nlen, ny = pushY / nlen;            /* outward normal  */
      float mdotn = (float)xAmount * nx + (float)yAmount * ny;
      float tx = (float)xAmount - mdotn * nx;                /* tangential part */
      float ty = (float)yAmount - mdotn * ny;
      float tmag = sqrtf(tx * tx + ty * ty);
      float mmag = sqrtf((float)(xAmount * xAmount + yAmount * yAmount));
      float add  = (mmag - tmag) * SLIP;     /* glide needed for full wall speed */
      if (tmag > 0.001f && add > 0.0f) {
        int gx = (int)(tx / tmag * add), gy = (int)(ty / tmag * add);
        int nxp = (int)(*value)->x + gx, nyp = (int)(*value)->y + gy;
        if (nxp < 0) nxp = 0; else if (nxp > WORLD_MAX) nxp = WORLD_MAX;
        if (nyp < 0) nyp = 0; else if (nyp > WORLD_MAX) nyp = WORLD_MAX;
        (*value)->x = (WORLD)nxp; (*value)->y = (WORLD)nyp;
        bumptype |= tankNudgeBuildings(sim, value, (int) sim->rules.tank_nudge_iterations);
      }
    }
    /* Expose a wall-stuck signal to brains via tank_obstructed (read by
     * Lua/ML observations). Same definition as the legacy path: a solid-wall
     * collision that left the tank in the grid cell it started this nudge in
     * — i.e. the wall blocked it rather than letting it slide. Sliding along
     * a wall moves to a new grid cell and is NOT obstructed. Circle mode does
     * not apply the legacy collision slowdown; this only sets the flag. */
    if (movedThisTick) {
      (*value)->obstructed = (bumptype & BumpInfo_SolidWall) &&
          (((*value)->x & TANK_GRID_MASK) == oldX) &&
          (((*value)->y & TANK_GRID_MASK) == oldY);
    }
  }
#else
  WORLD oldX = (*value)->x & TANK_GRID_MASK;
  WORLD oldY = (*value)->y & TANK_GRID_MASK;
  BumpInfo bumptype = tankNudgeBuildings(sim, value, (int) sim->rules.tank_nudge_iterations);

  /* Step 5 — Slow down from collisions (not shore or boat — shore slowdown
   * is handled by terrain speed limits, and boat tiles should not slow a
   * boat at all; the boat-on-boat destruction is handled in Step 9) */
  if (movedThisTick) {
    bool tankObstructed = (bumptype >= BumpInfo_SolidWall) &&
        (((*value)->x & TANK_GRID_MASK) == oldX) &&
        (((*value)->y & TANK_GRID_MASK) == oldY);
    if (tankObstructed) {
      if ((*value)->speed < sim->rules.tank_min_move) (*value)->speed = 0;
      else (*value)->speed -= sim->rules.tank_min_move;
    }
    (*value)->obstructed = tankObstructed;
  }
#endif

  /* Step 6 — Terrain constraints */
  {
    WORLD newmx = (*value)->x;
    WORLD newmy = (*value)->y;
    newmx >>= TANK_SHIFT_MAPSIZE;
    newmy >>= TANK_SHIFT_MAPSIZE;
    newbmx = (BYTE) newmx;
    newbmy = (BYTE) newmy;

    if (sim->isTutorial) {
      if (!isServer) {
        /* Client dialog sequencer: `<=` so the first step also fires
         * when the tank spawns on a trigger row without ever "entering"
         * it from above. Client-side speed=0 is cosmetic for prediction. */
        if (newbmy <= bmy) {
          if (frontEndTutorial(newbmy) == TRUE) {
            (*value)->speed = 0;
          }
        }
      } else {
        /* Server-authoritative stop: halt only at a stop row the player
         * hasn't passed yet (newbmy < tutorialMinRow), and only on row entry
         * so the tank isn't pinned once the dialog closes. After a death the
         * tank respawns higher and drives back down through already-seen rows;
         * those must not stop it again — only rows deeper than any reached so
         * far (i.e. messages not yet shown) do. */
        if (newbmy < bmy && newbmy < sim->tutorialMinRow &&
            tutorialIsStopPos(newbmy)) {
          (*value)->speed = 0;
        }
        /* Record the deepest row reached so passed stops stay passed. */
        if (newbmy < sim->tutorialMinRow) {
          sim->tutorialMinRow = newbmy;
        }
      }
    }
    if (isServer) {
      tankCheckPillCapture(sim, value);
    }
  }

  /* Step 7 — Mine sweeping (3-direction forward sweep) */
  tankNearMines(sim, bmx, bmy, ang);

  /* Step 8 — Position update and network sync */

  /* Check for scroll of screen */
  if (!isServer) {
    clientSimTankScroll((struct ClientSim *)sim);
  }

  /* Step 9 — Boat/water handling (server-authoritative) */
  if (!sim->isPredicting) {
    newbmx = (BYTE)((*value)->x >> TANK_SHIFT_MAPSIZE);
    newbmy = (BYTE)((*value)->y >> TANK_SHIFT_MAPSIZE);
    BYTE terrain9 = mapGetPos(mp, newbmx, newbmy);

    if ((*value)->boatState == BoatState_InBoat) {
      /* 7a: InBoat */
      if (terrain9 == RIVER) {
        /* Still on river — update last known river position */
        (*value)->lastBoatRiverX = newbmx;
        (*value)->lastBoatRiverY = newbmy;
      } else if (terrain9 == BOAT) {
        /* Destroy boat tile */
        mapSetPos(sim, mp, newbmx, newbmy, RIVER, TRUE, FALSE);
        explosionsAddItem(&sim->expl, newbmx, newbmy, 0, 0, EXPLOSION_START);
        if (sim->callbacks.explosion) sim->callbacks.explosion(sim->callbacks.ctx, newbmx, newbmy, 0, 0);
        sim->callbacks.soundDist(sim->callbacks.ctx, shotBuildingNear, newbmx, newbmy);
        if (!isServer) { clientSimRecalc((struct ClientSim *)sim); }
      }

      /* Lookahead bank clamp: hold tank center (WORLD) sim->rules.tank_boat_exit_inset inside
       * the river tile when an adjacent tile is soft land. Without this,
       * the body extends ~half a tile into the bank before the center
       * crosses and triggers the per-axis revert below. Skipped for
       * road/halfbuilding (slow exit onto road still works) and for
       * BOAT (allows pickup of an adjacent parked boat). Skipped at
       * the tank's own boat-exit speed so deliberate fast exits work. */
      if ((*value)->speed < tankBoatExitSpeed(sim, *value) &&
          mapIsLand(mp, pb, bs, newbmx, newbmy) == FALSE) {
        WORLD rMinX = ((WORLD)newbmx) << TANK_SHIFT_MAPSIZE;
        WORLD rMaxX = (((WORLD)newbmx + 1) << TANK_SHIFT_MAPSIZE) - 1;
        WORLD rMinY = ((WORLD)newbmy) << TANK_SHIFT_MAPSIZE;
        WORLD rMaxY = (((WORLD)newbmy + 1) << TANK_SHIFT_MAPSIZE) - 1;
        BYTE adj;
        if (newbmx > 0 && mapIsLand(mp, pb, bs, newbmx - 1, newbmy)) {
          adj = mapGetPos(mp, newbmx - 1, newbmy);
          if (adj != ROAD && adj != HALFBUILDING && adj != BOAT) {
            if ((*value)->x < rMinX + (WORLD) sim->rules.tank_boat_exit_inset) (*value)->x = rMinX + (WORLD) sim->rules.tank_boat_exit_inset;
          }
        }
        if (newbmx < 255 && mapIsLand(mp, pb, bs, newbmx + 1, newbmy)) {
          adj = mapGetPos(mp, newbmx + 1, newbmy);
          if (adj != ROAD && adj != HALFBUILDING && adj != BOAT) {
            if ((*value)->x > rMaxX - (WORLD) sim->rules.tank_boat_exit_inset) (*value)->x = rMaxX - (WORLD) sim->rules.tank_boat_exit_inset;
          }
        }
        if (newbmy > 0 && mapIsLand(mp, pb, bs, newbmx, newbmy - 1)) {
          adj = mapGetPos(mp, newbmx, newbmy - 1);
          if (adj != ROAD && adj != HALFBUILDING && adj != BOAT) {
            if ((*value)->y < rMinY + (WORLD) sim->rules.tank_boat_exit_inset) (*value)->y = rMinY + (WORLD) sim->rules.tank_boat_exit_inset;
          }
        }
        if (newbmy < 255 && mapIsLand(mp, pb, bs, newbmx, newbmy + 1)) {
          adj = mapGetPos(mp, newbmx, newbmy + 1);
          if (adj != ROAD && adj != HALFBUILDING && adj != BOAT) {
            if ((*value)->y > rMaxY - (WORLD) sim->rules.tank_boat_exit_inset) (*value)->y = rMaxY - (WORLD) sim->rules.tank_boat_exit_inset;
          }
        }
      }

      /* Center on land — leave boat */
      if ((*value)->boatState == BoatState_InBoat &&
          mapIsLand(mp, pb, bs, newbmx, newbmy) == TRUE) {
        BYTE landTerrain = mapGetPos(mp, newbmx, newbmy);
        if (landTerrain == ROAD || landTerrain == BUILDING || landTerrain == HALFBUILDING) {
          /* Hard surface — instant exit, no grace zone.
           * Only drop boat if last river tile is adjacent (deep sea→land skip) */
          if (abs(newbmx - (*value)->lastBoatRiverX) + abs(newbmy - (*value)->lastBoatRiverY) <= 2) {
            if (mapGetPos(mp, (*value)->lastBoatRiverX, (*value)->lastBoatRiverY) == RIVER) {
              mapSetPos(sim, mp, (*value)->lastBoatRiverX, (*value)->lastBoatRiverY, BOAT, TRUE, FALSE);
            }
          }
          (*value)->boatState = BoatState_NotOnBoat;
          (*value)->onBoat = FALSE;
          if (!isServer) { clientSimRecalc((struct ClientSim *)sim); }
        } else if ((*value)->speed >= tankBoatExitSpeed(sim, *value)) {
          /* Fast approach on soft terrain — instant exit.
           * Only drop boat if last river tile is adjacent (deep sea→land skip) */
          if (abs(newbmx - (*value)->lastBoatRiverX) + abs(newbmy - (*value)->lastBoatRiverY) <= 2) {
            if (mapGetPos(mp, (*value)->lastBoatRiverX, (*value)->lastBoatRiverY) == RIVER) {
              mapSetPos(sim, mp, (*value)->lastBoatRiverX, (*value)->lastBoatRiverY, BOAT, TRUE, FALSE);
            }
          }
          (*value)->boatState = BoatState_NotOnBoat;
          (*value)->onBoat = FALSE;
          if (!isServer) { clientSimRecalc((struct ClientSim *)sim); }
          if (mapIsMine(mp, newbmx, newbmy) == TRUE) {
            minesExpAddItem(sim, &sim->minesExplosions, mp, newbmx, newbmy);
          }
        } else {
          /* Soft terrain, slow approach — per-axis position revert.
           * Tank stays on the starting river tile until speed reaches
           * its boat-exit speed. Sliding along the bank works because
           * the parallel axis isn't blocked. Mirrors original WinBolo
           * boat-exit behavior. */
          WORLD rMinX = ((WORLD)bmx) << TANK_SHIFT_MAPSIZE;
          WORLD rMaxX = (((WORLD)bmx + 1) << TANK_SHIFT_MAPSIZE) - 1;
          WORLD rMinY = ((WORLD)bmy) << TANK_SHIFT_MAPSIZE;
          WORLD rMaxY = (((WORLD)bmy + 1) << TANK_SHIFT_MAPSIZE) - 1;
          bool xCrossed = (newbmx != bmx) && mapIsLand(mp, pb, bs, newbmx, bmy);
          bool yCrossed = (newbmy != bmy) && mapIsLand(mp, pb, bs, bmx, newbmy);
          /* Diagonal corner-cross fallback: if neither single-axis path
           * explains the land tile, revert both. */
          if (!xCrossed && !yCrossed) { xCrossed = TRUE; yCrossed = TRUE; }
          if (xCrossed) {
            if ((*value)->x < rMinX) (*value)->x = rMinX;
            else if ((*value)->x > rMaxX) (*value)->x = rMaxX;
          }
          if (yCrossed) {
            if ((*value)->y < rMinY) (*value)->y = rMinY;
            else if ((*value)->y > rMaxY) (*value)->y = rMaxY;
          }
        }
      }

      /* Check for hit mine on outer map edges */
      if ((*value)->boatState == BoatState_InBoat && mapIsMine(mp, bmx, bmy) == TRUE) {
        sim->callbacks.soundDist(sim->callbacks.ctx, mineExplosionNear, bmx, bmy);
        explosionsAddItem(&sim->expl, bmx, bmy, 0, 0, EXPLOSION_START);
        if (sim->callbacks.explosion) sim->callbacks.explosion(sim->callbacks.ctx, bmx, bmy, 0, 0);
        (*value)->boatState = BoatState_NotOnBoat;
        (*value)->onBoat = FALSE;
        (*value)->speed = 0;
      }

    } else if ((*value)->boatState == BoatState_LeavingBoat) {
      /* 7b: LeavingBoat */
      if (terrain9 == RIVER &&
          (newbmx != (*value)->lastBoatRiverX || newbmy != (*value)->lastBoatRiverY)) {
        /* Back on a different river tile — actually returned to water */
        (*value)->boatState = BoatState_InBoat;
        (*value)->lastBoatRiverX = newbmx;
        (*value)->lastBoatRiverY = newbmy;
      } else if (terrain9 == BOAT) {
        /* Destroy boat tile and return to InBoat */
        mapSetPos(sim, mp, newbmx, newbmy, RIVER, TRUE, FALSE);
        (*value)->boatState = BoatState_InBoat;
        (*value)->lastBoatRiverX = newbmx;
        (*value)->lastBoatRiverY = newbmy;
      } else if (mapIsMine(mp, newbmx, newbmy) == TRUE) {
        /* Mine on current land tile — explode and lose boat */
        minesExpAddItem(sim, &sim->minesExplosions, mp, newbmx, newbmy);
        (*value)->boatState = BoatState_NotOnBoat;
        (*value)->onBoat = FALSE;
        if (!isServer) { clientSimRecalc((struct ClientSim *)sim); }
      }

    } else {
      /* 7c: NotOnBoat — on land */
      /* Check for entering Boat */
      if (terrain9 == BOAT) {
        mapSetPos(sim, mp, newbmx, newbmy, RIVER, TRUE, FALSE);
        (*value)->onBoat = TRUE;
        (*value)->boatState = BoatState_InBoat;
        (*value)->lastBoatRiverX = newbmx;
        (*value)->lastBoatRiverY = newbmy;
        if (!isServer) { clientSimRecalc((struct ClientSim *)sim); }
      }

      /* Check for hit mine */
      if (newbmx != bmx || newbmy != bmy) {
        if (mapIsMine(mp, newbmx, newbmy) == TRUE) {
          minesExpAddItem(sim, &sim->minesExplosions, mp, newbmx, newbmy);
        }
      }

      /* Check for tank in water. The wading test is the river's own cap:
         one number answers both how fast a tank may cross a river and how
         slow it has to be going to be in the water rather than on it. */
      if (terrain9 == RIVER && (*value)->speed <= (SPEEDTYPE) sim->rules.speed_river && (*value)->boatState == BoatState_NotOnBoat) {
        if (basesExistPos(bs, newbmx, newbmy) == FALSE) {
          (*value)->waterCount++;
          if ((*value)->waterCount == sim->rules.tank_water_ticks) {
            (*value)->waterCount = 0;
            tankInWater(sim, value);
          }
        }
      }

      /* Check for capture base */
      if (isServer == TRUE) {
        if (baseIsCapturable(sim, bs, newbmx, newbmy) == TRUE) {
          if (playersCheckSameSquare(&sim->plyrs, gameSimGetTankPlayer(sim, value), newbmx, newbmy) == FALSE) {
            if (basesAmOwner(sim, gameSimGetTankPlayer(sim, value), newbmx, newbmy) == FALSE) {
              BYTE baseNum = basesGetBaseNum(bs, newbmx, newbmy);
              /* The base is capturable and the tank is entitled to it; the
               * host decides whether it actually changes hands. A refusal
               * only holds the owner — the tank is already on the square and
               * drives on.
               * basesGetBaseNum counts from one and the rest of this block
               * wants it that way; the policy surface counts from zero, so
               * the question takes one off. Leave the subtraction alone. */
              if (gameSimCanCapture(sim, CAPTURE_KIND_BASE, (BYTE)(baseNum - 1),
                                    gameSimGetTankPlayer(sim, value)) != FALSE) {
                basesSetOwner(sim, newbmx, newbmy, gameSimGetTankPlayer(sim, value), FALSE);
                if (!isServer) {
                  frontEndStatusBase(clientSimFromSim(sim), baseNum, (basesGetStatusNum(sim, baseNum)));
                }
                if (!isServer) { clientSimRecalc((struct ClientSim *)sim); }
              }
            }
          }
        }
      }

      /* Check for pb capture */
      if (isServer == TRUE) {
        tankCheckPillCapture(sim, value);
      }
    }
  }
  /* Mine reveal is display-only — must run during prediction so placed mines are visible */
  tankNearMines(sim, bmx, bmy, ang);
}

/*********************************************************
*NAME:          tankTurn
*AUTHOR:        John Morrison
*CREATION DATE: 13/1/99
*LAST MODIFIED: 13/1/99
*PURPOSE:
*  Function called to update the tanks facing angle
*
*ARGUMENTS:
*  value  - Pointer to the tank structure
*  mp     - Pointer to the map structure
*  pb     - Pointer to the pillbox structure
*  bs     - Pointer to the bases structure
*  bmx    - X Map Position
*  bmy    - Y Map position
*  tb     - The tank buttons being pressed
*********************************************************/
void tankTurn(GameSim *sim, tank *value, BYTE bmx, BYTE bmy, tankButton tb) {
  map *mp = &sim->mp;
  pillboxes *pb = &sim->pb;
  bases *bs = &sim->bs;
  TURNTYPE turnAmount; /* Amount to turn */
  /* Scales the terrain's turn rate before the ramp below, so a modified tank
     ramps up over the same six ticks. */
  int turnPct = tankModPct((*value)->mods.turn);

  /* Left turn */
  if (tb == TLEFT || tb == TLEFTACCEL || tb == TLEFTDECEL) {
    turnAmount = mapGetTurnRate(sim,mp,pb,bs,bmx,bmy,(*value)->onBoat, gameSimGetTankPlayer(sim, value)) * turnPct / 100;
    if ((*value)->firstLeft < 6) {
      (*value)->firstLeft++;
      turnAmount /= 8;
    }
    (*value)->angle -= turnAmount;
    if ((*value)->angle < 0) {
      (*value)->angle = (TURNTYPE) (BRADIANS_MAX + (*value)->angle);
    }
  } else {
    (*value)->firstLeft = 0;
  }
  /* Right Turn */
  if (tb == TRIGHT || tb == TRIGHTACCEL || tb == TRIGHTDECEL) {
    turnAmount = mapGetTurnRate(sim,mp,pb,bs,bmx,bmy,(*value)->onBoat, gameSimGetTankPlayer(sim, value)) * turnPct / 100;
    if ((*value)->firstRight < 6) {
      (*value)->firstRight++;
      turnAmount /= 8;
    }
    (*value)->angle += turnAmount;
    if ((*value)->angle > BRADIANS_MAX) {
      (*value)->angle = (TURNTYPE) ((*value)->angle - BRADIANS_MAX);
    }
  } else {
    (*value)->firstRight = 0;
  }
}

/*********************************************************
*NAME:          tankAccel
*AUTHOR:        John Morrison
*CREATION DATE: 13/1/99
*LAST MODIFIED: 13/1/99
*PURPOSE:
* Apply accleration or decalleration as required
*
*ARGUMENTS:
*  value  - Pointer to the tank structure
*  mp     - Pointer to the map structure
*  pb     - Pointer to the pillbox structure
*  bs     - Pointer to the bases structure
*  bmx    - X Map Position
*  bmy    - Y Map position
*  tb     - The tank buttons being pressed
*********************************************************/
void tankAccel(GameSim *sim, tank *value, BYTE bmx, BYTE bmy, tankButton tb) {
  map *mp = &sim->mp;
  pillboxes *pb = &sim->pb;
  bases *bs = &sim->bs;
  BYTE rawCap;             /* Terrain's own cap for this square */
  SPEEDTYPE displace;      /* That cap once the tank's speed modifier applies */
  SPEEDTYPE subAmount;     /* Amount to subtract */
  int accelPct = tankModPct((*value)->mods.accel);
  /* Both rates scale together: the accel modifier is how fast speed changes
     in either direction, not how fast it rises. */
  SPEEDTYPE terrainDecel = (SPEEDTYPE) (sim->rules.tank_decel_rate * accelPct / 100);
  SPEEDTYPE slowKeyRate = (SPEEDTYPE) (sim->rules.tank_brake_rate * accelPct / 100);

  rawCap = mapGetSpeed(sim,mp,pb,bs,bmx,bmy,(*value)->onBoat, gameSimGetTankPlayer(sim, value));
  displace = (SPEEDTYPE) ((rawCap * tankModPct((*value)->mods.speed)) / 100);
  /* Ground the tank can cross stays crossable however slow it has been made:
     a cap that scales away to nothing becomes the smallest cap that moves. */
  if (rawCap > 0 && displace < 1) {
    displace = 1;
  }
  if ((tb == TDECEL || tb == TLEFTDECEL || tb == TRIGHTDECEL) || (*value)->speed > displace)  {
    subAmount = (*value)->speed;
    if ((*value)->speed > displace) {
      subAmount = (SPEEDTYPE) ((*value)->speed - terrainDecel);
    }
    if (tb == TDECEL || tb == TLEFTDECEL || tb == TRIGHTDECEL) {
      subAmount -= slowKeyRate;
    }
    if (subAmount > (*value)->speed) {
      ((*value)->speed) = 0;
    } else {
      (*value)->speed = subAmount;
      if ((*value)->speed < 0) {
        (*value)->speed = 0;
      }
    }
  } else if ((*value)->speed < displace && (tb == TACCEL || tb == TLEFTACCEL || tb == TRIGHTACCEL))  {
    ((*value)->speed) += sim->rules.tank_accel_rate * accelPct / 100;
    if ((*value)->speed > displace) {
      (*value)->speed = displace;
    }
  }
}

bool pillsIsCapturable(pillboxes *value, BYTE xValue, BYTE yValue);

/*********************************************************
*NAME:          tankCheckPillCapture
*AUTHOR:        John Morrison
*CREATION DATE: 15/1/99
*LAST MODIFIED: 23/6/00
*PURPOSE:
* Function checks for pillbox captures. If it does capture
* one then it updates everything.
*
*ARGUMENTS:
*  value  - Pointer to the tank structure
*  pb     - Pointer to the pillbox structure
*********************************************************/
void tankCheckPillCapture(GameSim *sim, tank *value) {
	pillboxes *pb = &sim->pb;
	bool isServer = sim->isServer;
	BYTE bmx;       /* MAP x-coord of the probe being tested */
	BYTE bmy;       /* MAP y-coord of the probe being tested */
	BYTE pillNum;   /* The pill number */
	bool captured = FALSE;
	int p;

	/* Tank is alive and we are either in a server context or a non-network game */
	if (!(*value)->destroyed && (isServer)) {
		/* Pickup tests a small box around the tank centre ((WORLD) sim->rules.tank_pill_pickup_inset
		 * each way): the centre, four edge midpoints and four corners. Much
		 * smaller than the tank's collision footprint so a pill isn't grabbed
		 * from a mere graze, but still "any part overlaps" rather than
		 * centre-only, giving a little tolerance so a dead pill the building-nudge
		 * keeps the centre a hair outside is still reachable. A live pill or wall
		 * is solid, so the box can't reach one past a wall. */
		WORLD tankX = (*value)->x;
		WORLD tankY = (*value)->y;
		WORLD top    = tankY - (WORLD) sim->rules.tank_pill_pickup_inset;
		WORLD bottom = tankY + (WORLD) sim->rules.tank_pill_pickup_inset;
		WORLD left   = tankX - (WORLD) sim->rules.tank_pill_pickup_inset;
		WORLD right  = tankX + (WORLD) sim->rules.tank_pill_pickup_inset;
		/* centre, 4 edge midpoints, 4 corners */
		WORLD probeX[9] = { tankX, tankX, tankX, left,  right, right, right,  left,   left };
		WORLD probeY[9] = { tankY, top,   bottom, tankY, tankY, top,   bottom, bottom, top  };
		/* A square the host refused this tick; several probes land on one
		 * square, and a refused pill stays capturable, so without this the
		 * same question would be put up to nine times per tick. */
		bool refused = FALSE;
		BYTE refusedX = 0;
		BYTE refusedY = 0;

		for (p = 0; p < 9; p++) {
			bmx = (BYTE)(probeX[p] >> TANK_SHIFT_MAPSIZE);
			bmy = (BYTE)(probeY[p] >> TANK_SHIFT_MAPSIZE);
			if (refused && bmx == refusedX && bmy == refusedY) {
				continue;
			}

			/* The probe is not at the origin and the pill is capturable. A
			 * tile captured by an earlier probe is already inTank, so
			 * pillsIsCapturable rejects it and duplicate probe tiles are
			 * harmless. */
			if (bmx != 0 && bmy != 0 && pillsIsCapturable(pb, bmx,bmy) == TRUE) {
				pillNum = pillsGetPillNum(pb, bmx, bmy, TRUE, FALSE);
				/* The engine's own test has passed; the host has the last
				 * word on whether the pill changes hands. Asked once for the
				 * square, before anything is taken, so a refusal leaves the
				 * pill where it is and the tank drives on over it.
				 * pillsGetPillNum counts from one and tankTakePill below
				 * wants it that way; the policy surface counts from zero, so
				 * the question takes one off. Leave the subtraction alone. */
				if (pillNum != PILL_NOT_FOUND &&
				    gameSimCanCapture(sim, CAPTURE_KIND_PILL, (BYTE)(pillNum - 1),
				                      gameSimGetTankPlayer(sim, value)) == FALSE) {
					refused = TRUE;
					refusedX = bmx;
					refusedY = bmy;
					continue;
				}
				while (pillNum != PILL_NOT_FOUND) {
					tankTakePill(sim, value, pillNum);
					if (pillsExistPos(pb, bmx, bmy) == TRUE) {
						pillNum = pillsGetPillNum(pb, bmx, bmy, TRUE, FALSE);
					} else {
						pillNum = PILL_NOT_FOUND;
					}
				}
				captured = TRUE;
			}
		}
		if (captured && !sim->isServer) { clientSimRecalc((struct ClientSim *)sim); }
	}
}

/*********************************************************
*NAME:          tankTakePill
*PURPOSE:
* Puts one pillbox into a tank: marks it carried, tells the
* host so the pickup is recorded, adds it to the tank's
* carry list and moves the ownership across. The caller
* decides whether the pill may be taken; this is what
* taking it does.
*
*ARGUMENTS:
*  sim     - The game the tank belongs to
*  value   - Pointer to the tank structure
*  pillNum - The pillbox number, counted from 1
*********************************************************/
void tankTakePill(GameSim *sim, tank *value, BYTE pillNum) {
  pillboxes *pb = &sim->pb;
  pillbox p;      /* The pill, read for the square the pickup is recorded at */

  memset(&p, 0, sizeof(p));
  pillsGetPill(pb, &p, pillNum);
  pillsSetPillInTank(pb, pillNum, TRUE);
  if (sim->callbacks.recordPillPickup) {
    sim->callbacks.recordPillPickup(sim->callbacks.ctx, gameSimGetTankPlayer(sim, value), pillNum, p.x, p.y);
  }
  tankPutPill(sim, value, pillNum);
  if ((pillsGetPillOwner(pb, pillNum)) != gameSimGetTankPlayer(sim, value)) {
    pillsSetPillOwner(sim, pb, pillNum, gameSimGetTankPlayer(sim, value), FALSE);
  }
}

/*********************************************************
*NAME:          tankDropPillAt
*PURPOSE:
* Drops one carried pillbox on a named map square. Answers
* FALSE and changes nothing when the square will not hold a
* pill — off the minable area, or already holding a pill, a
* base, a building, a half-building or a boat — so a caller
* laying several out can move along and try the next one.
* The pill lands dead, owned by the tank that carried it,
* at the normal firing interval.
*
*ARGUMENTS:
*  sim     - The game the tank belongs to
*  value   - Pointer to the tank structure
*  pillNum - The pillbox number, counted from 1
*  mx      - X map square to drop it on
*  my      - Y map square to drop it on
*********************************************************/
bool tankDropPillAt(GameSim *sim, tank *value, BYTE pillNum, BYTE mx, BYTE my) {
  map *mp = &sim->mp;
  pillboxes *pb = &sim->pb;
  bases *bs = &sim->bs;
  bool isServer = sim->isServer;
  pillbox item;   /* Item to add to the pillbox */
  BYTE pos;       /* The Map position */

  if (mx <= MAP_MINE_EDGE_LEFT || mx >= MAP_MINE_EDGE_RIGHT ||
      my <= MAP_MINE_EDGE_TOP || my >= MAP_MINE_EDGE_BOTTOM) {
    return FALSE;
  }
  pos = mapGetPos(mp, mx, my);
  if (pillsExistPos(pb, mx, my) == TRUE || basesExistPos(bs, mx, my) == TRUE ||
      pos == BUILDING || pos == HALFBUILDING || pos == BOAT) {
    return FALSE;
  }

  item.x = mx;
  item.y = my;
  item.armour = 0;
  item.owner = gameSimGetTankPlayer(sim, value);
  item.speed = (BYTE) sim->rules.pill_attack_ticks;
  item.reload = (BYTE) sim->rules.pill_attack_ticks;
  item.coolDown = 0;
  item.inTank = FALSE;
  item.justSeen = FALSE;
  if (isServer) {
    pillsSetPill(sim, pb,&item,pillNum);
    /* The same event a builder finishing the job raises: a pillbox that was
       being carried is on the map again. Every caller reaching here is a
       drop rather than a build — the tank sinking, the tank destroyed, the
       player leaving, or a scenario putting one down — so the armour byte
       this carries is 0 and that is what tells a listener it is not a live
       gun. pillNum counts from one; the event carries the 0-based slot. */
    if (sim->callbacks.pillPlaced && pillNum > 0) {
      sim->callbacks.pillPlaced(sim->callbacks.ctx, item.owner,
                                (BYTE)(pillNum - 1), mx, my,
                                pillsGetArmourPos(pb, mx, my));
    }
  }
  if (!isServer) {
    frontEndStatusPillbox(clientSimFromSim(sim), pillNum, (pillsGetAllianceNum(sim, pb, pillNum)));
  }
  tankGetCarriedPillNum(value, pillNum);
  return TRUE;
}

/*********************************************************
*NAME:          tankDropPills
*AUTHOR:        John Morrison
*CREATION DATE: 16/1/99
*LAST MODIFIED: 21/6/00
*PURPOSE:
* Drops all the pillboxes at the tanks current location.
* Called when tank dies
*
*ARGUMENTS:
*  value  - Pointer to the tank structure
*  mp     - Pointer to the map structure
*  pb     - Pointer to the pillbox structure
*  bs     - Pointer to the bases structure
*********************************************************/
void tankDropPills(GameSim *sim, tank *value) {
  bool isServer = sim->isServer;
  WORLD conv;     /* Used for conversion */
  BYTE bmx;       /* Current Position of Tank */
  BYTE bmy;
  BYTE numPills;  /* The number of pills on the tank */
  BYTE width;     /* How wide the pills length should be */
  tankCarryPb q;  /* Temp pointer for removing pills */
  BYTE count;     /* Looping variable */


  /* Get the number of pills on the tank */
  numPills = 0;
  q = (*value)->carryPills;
  while (NonEmpty(q)) {
    numPills++;
    q = TankPillsTail(q);
  }
  if (numPills > 0 && (isServer)) {
    count = 0;
    /* Get tank location */
    conv = (*value)->x;
    conv >>= TANK_SHIFT_MAPSIZE;
    bmx = (BYTE) conv;
    conv = (*value)->y;
    conv >>= TANK_SHIFT_MAPSIZE;
    bmy = (BYTE) conv;
    /* Get the width for depositing them */
    width = (BYTE) sqrt((double) numPills);
    bmx -= width/2;
    bmy -= width/2;

    if (bmx <= MAP_MINE_EDGE_LEFT) { /*bmx >= 0 is always true becuase of the data type.*/
      bmx = MAP_MINE_EDGE_LEFT+1;
    } else if (bmx >= MAP_MINE_EDGE_RIGHT) {
      bmx = MAP_MINE_EDGE_RIGHT - 10;
    }

    if (bmy <= MAP_MINE_EDGE_TOP) { /*bmx >= 0 is always true becuase of the data type.*/
      bmy = MAP_MINE_EDGE_TOP+1;
    } else if (bmy >= MAP_MINE_EDGE_BOTTOM) {
      bmy = MAP_MINE_EDGE_BOTTOM - 10;
    }

    while (NonEmpty((*value)->carryPills)) {
      q = (*value)->carryPills;
      if (isServer) {
        tankDropPillAt(sim, value, q->pillNum, bmx, (BYTE)(bmy+count));
        count++;
        if (count == width) {
          count = 0;
          bmx++;
        }
      } else {
//        (*value)->carryPills = TankPillsTail(q);
//        Dispose(q);
      }

    }
    if (!sim->isServer) { clientSimRecalc((struct ClientSim *)sim); }
  }
  return;
}

