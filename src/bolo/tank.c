void tankGetCarriedPillNum(tank *value, BYTE pillNum) {
  tankCarryPb q;
  tankCarryPb prev;
  bool done;
  done = FALSE;
  prev = NULL;
  q = (*value)->carryPills;
  while (!IsEmpty(q) && done == FALSE) {
    if (q->pillNum == pillNum) {
      done = TRUE;
      if (prev == NULL) {
        (*value)->carryPills = q->next;
      } else {
        prev->next = q->next;
      }
      Dispose(q);
    } else {
      prev = q;
      q = q->next;
    }
  }
}
