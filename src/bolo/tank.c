/*********************************************************
 * tankBasePredictedDrivable - Whether the client has already
 * worked out that the base on this square is dead, ahead of
 * the server telling it so.
 *
 * The client is masked out of a live enemy base's armour, so
 * without this the square stays solid until the death event
 * lands a round trip later while the server has already
 * driven the tank through — the client snaps forward each
 * snapshot and replays itself back into the wall. Once the
 * client's own predicted shell is due to drop the base to
 * base_capture_armour, both ends derive "drivable" from the
 * same rule at the same tick and there is nothing to correct.
 *
 * Compares against replayTick rather than the latest tick so
 * a reconciliation replay spanning the death still treats the
 * ticks before it as blocked. Always FALSE on the server and
 * outside prediction, where every field involved is 0.
 *********************************************************/
static bool tankBasePredictedDrivable(GameSim *sim, BYTE mx, BYTE my) {
  BYTE num, idx;

  if (sim->replayTick == 0) {
    return FALSE;
  }
  /* basesGetBaseNum answers 1-based, with BASE_NOT_FOUND for no base here. */
  num = basesGetBaseNum(&sim->bs, mx, my);
  if (num == BASE_NOT_FOUND || num == 0 || (BYTE)(num - 1) >= MAX_BASES) {
    return FALSE;
  }
  idx = (BYTE)(num - 1);
  if (sim->basePredictedDeadTick[idx] == 0) {
    return FALSE;
  }
  return sim->replayTick >= sim->basePredictedDeadTick[idx];
}

/*********************************************************
 * tankBuildingCollision - Check if a WORLD coordinate
 * collides with a solid object (building, pillbox, base).
 * Sets bumptype flags for the type of collision.
 *********************************************************/
static bool tankBuildingCollision(GameSim *sim, tank *value, WORLD x, WORLD y,
                                  BumpInfo *bumptype, bool isFirstBump) {
  map *mp = &sim->mp;
  pillboxes *pb = &sim->pb;
  bases *bs = &sim->bs;
  BYTE mx = x >> TANK_SHIFT_MAPSIZE;
  BYTE my = y >> TANK_SHIFT_MAPSIZE;
  BYTE terrain = mapGetPos(mp, mx, my);

  if (terrain == BUILDING || terrain == HALFBUILDING) {
    *bumptype |= BumpInfo_SolidWall;
    return TRUE;
  }

  if (pillsExistPos(pb, mx, my) == TRUE) {
    BYTE armour = pillsGetArmourPos(pb, mx, my);
    if (armour != PILL_NOT_FOUND && armour > 0) {
      *bumptype |= BumpInfo_SolidWall;
      return TRUE;
    }
  }

  if (basesExistPos(bs, mx, my) == TRUE) {
    if (basesCantDrive(sim, mx, my, gameSimGetTankPlayer(sim, value)) == TRUE &&
        tankBasePredictedDrivable(sim, mx, my) == FALSE) {
      *bumptype |= BumpInfo_SolidWall;
      return TRUE;
    }
  }

  if (isFirstBump == TRUE && (*value)->boatState == BoatState_InBoat) {
    if (terrain == BOAT) {
      *bumptype |= BumpInfo_Boat;
    } else if (terrain != RIVER && terrain != DEEP_SEA) {
      *bumptype |= BumpInfo_Shore;
    }
  }

  return FALSE;
}

/*********************************************************
 * tankNudgeOtherTanks - Iteratively nudge this tank away
 * from all other living tanks that overlap.
 *********************************************************/
static void tankNudgeOtherTanks(GameSim *sim, tank *value) {
  BYTE myPlayer = gameSimGetTankPlayer(sim, value);
  BYTE t;

  for (t = 0; t < MAX_TANKS; t++) {
    if (t == myPlayer || sim->tanks[t] == NULL) continue;
    tank other = sim->tanks[t];
    if (other->destroyed) continue;

    int j;
    for (j = 0; j < sim->rules.tank_nudge_iterations; j++) {
      const WORLD step = (WORLD) sim->rules.tank_nudge_amount;
      int dx = abs((*value)->x - other->x);
      int dy = abs((*value)->y - other->y);
      if (dx + dy >= sim->rules.tank_collision_distance) break;

      if (dx > sim->rules.tank_nudge_threshold) {
        if ((*value)->x < other->x)
          (*value)->x = ((*value)->x - step) | TANK_GRID_LOW_MASK;
        else
          (*value)->x = ((*value)->x + step) & TANK_GRID_MASK;
      } else {
        if ((*value)->y < other->y)
          (*value)->y = ((*value)->y - step) | TANK_GRID_LOW_MASK;
        else
          (*value)->y = ((*value)->y + step) & TANK_GRID_MASK;
      }
    }
  }
}

/*********************************************************
 * tankNudgeBuildings - Iteratively nudge tank out of
 * building collisions using the direction-dependent
 * bounding box. Returns accumulated BumpInfo flags.
 *********************************************************/
static BumpInfo tankNudgeBuildings(GameSim *sim, tank *value, int maxNudges) {
  BumpInfo bumptype = BumpInfo_None;
  bool isFirstBump = TRUE;

#ifndef BOLO_LEGACY_SQUARE_COLLISION
  /* Circle-vs-AABB resolver (default). The tank is a circle of radius
   * tank_hit_radius; each solid map tile is a 256-WU axis-aligned box. Each
   * pass, push the circle out of every overlapping solid tile along its
   * minimum-translation vector (toward the closest point on the box).
   * Perpendicular push with the tangential component untouched = smooth
   * sliding along walls and around corners. */
  const int R    = (int) sim->rules.tank_hit_radius;
  const int TILE = 1 << TANK_SHIFT_MAPSIZE;
  int cx = (int)(*value)->x, cy = (int)(*value)->y;
  int pass;
  for (pass = 0; pass < maxNudges; pass++) {
    int cmx = cx >> TANK_SHIFT_MAPSIZE;
    int cmy = cy >> TANK_SHIFT_MAPSIZE;
    int moved = 0, gx, gy;
    for (gy = cmy - 1; gy <= cmy + 1; gy++) {
      for (gx = cmx - 1; gx <= cmx + 1; gx++) {
        BumpInfo bt = BumpInfo_None;
        int minX, maxX, minY, maxY, qx, qy, dx, dy, d2;
        if (gx < 0 || gy < 0 || gx > 255 || gy > 255) continue;
        if (!tankBuildingCollision(sim, value,
              (WORLD)((gx << TANK_SHIFT_MAPSIZE) + TILE / 2),
              (WORLD)((gy << TANK_SHIFT_MAPSIZE) + TILE / 2), &bt, isFirstBump))
          continue;                              /* tile not solid */
        minX = gx << TANK_SHIFT_MAPSIZE; maxX = minX + TILE;
        minY = gy << TANK_SHIFT_MAPSIZE; maxY = minY + TILE;
        qx = cx < minX ? minX : (cx > maxX ? maxX : cx);  /* closest point */
        qy = cy < minY ? minY : (cy > maxY ? maxY : cy);
        dx = cx - qx; dy = cy - qy;
        d2 = dx * dx + dy * dy;
        if (d2 >= R * R) continue;               /* solid but circle clears it */
        bumptype |= bt;                          /* genuine collision */
        if (d2 > 0) {
          float dist = sqrtf((float)d2);
          float scale = ((float)R - dist) / dist;
          cx += (int)(dx * scale);
          cy += (int)(dy * scale);
        } else {
          /* center inside the box: eject along the shallowest edge */
          int pL = cx - minX, pR = maxX - cx, pT = cy - minY, pB = maxY - cy;
          int m = pL, ax = 0;
          if (pR < m) { m = pR; ax = 1; }
          if (pT < m) { m = pT; ax = 2; }
          if (pB < m) { m = pB; ax = 3; }
          if      (ax == 0) cx -= (m + R);
          else if (ax == 1) cx += (m + R);
          else if (ax == 2) cy -= (m + R);
          else              cy += (m + R);
        }
        moved = 1;
      }
    }
    isFirstBump = FALSE;
    if (!moved) break;
  }
  if (cx < 0) cx = 0; else if (cx > WORLD_MAX) cx = WORLD_MAX;
  if (cy < 0) cy = 0; else if (cy > WORLD_MAX) cy = WORLD_MAX;
  (*value)->x = (WORLD)cx;
  (*value)->y = (WORLD)cy;
  return bumptype;
#else
  /* Legacy direction-dependent bounding-box grid-snap nudge. */
  const TankBoundingBox *table = (*value)->onBoat ? tank_bbox_boat : tank_bbox_land;
  BYTE dirIndex = utilGetDir((*value)->angle);
  const TankBoundingBox *fc = &table[dirIndex];
  /* Convert margin-from-edge to distance-from-center:
   * For a 16px sprite, center is at pixel 8.
   * distance_from_center = (8 - margin) pixels, then scale to WORLD units (<< 4) */
  WORLD topInset    = (8 - fc->top)    << 4;
  WORLD bottomInset = (8 - fc->bottom) << 4;
  WORLD leftInset   = (8 - fc->left)   << 4;
  WORLD rightInset  = (8 - fc->right)  << 4;
  int i;

  WORLD tankX = (*value)->x;
  WORLD tankY = (*value)->y;

  for (i = 0; i < maxNudges; i++) {
    WORLD top    = tankY - topInset;
    WORLD bottom = tankY + bottomInset;
    WORLD left   = tankX - leftInset;
    WORLD right  = tankX + rightInset;
    BYTE nudgebits = 0;

    /* Check 4 orthogonal edge midpoints */
    if (tankBuildingCollision(sim, value, tankX, top, &bumptype, isFirstBump))
      nudgebits |= 1;
    if (tankBuildingCollision(sim, value, right, tankY, &bumptype, isFirstBump))
      nudgebits |= 2;
    if (tankBuildingCollision(sim, value, tankX, bottom, &bumptype, isFirstBump))
      nudgebits |= 4;
    if (tankBuildingCollision(sim, value, left, tankY, &bumptype, isFirstBump))
      nudgebits |= 8;

    /* If no orthogonal collision, check 4 diagonal corners.
     * Only nudge on the axis with less penetration so the
     * tank slides along the wall instead of getting stuck. */
    if (nudgebits == 0) {
      if (tankBuildingCollision(sim, value, right, top, &bumptype, isFirstBump)) {
        WORLD overX = right - ((right >> 8) << 8);       /* penetration into tile from left edge */
        WORLD overY = (((top >> 8) + 1) << 8) - 1 - top; /* penetration into tile from bottom edge */
        nudgebits |= (overX <= overY) ? 0x2 : 0x1;
      }
      if (tankBuildingCollision(sim, value, right, bottom, &bumptype, isFirstBump)) {
        WORLD overX = right - ((right >> 8) << 8);
        WORLD overY = bottom - ((bottom >> 8) << 8);
        nudgebits |= (overX <= overY) ? 0x2 : 0x4;
      }
      if (tankBuildingCollision(sim, value, left, bottom, &bumptype, isFirstBump)) {
        WORLD overX = (((left >> 8) + 1) << 8) - 1 - left;
        WORLD overY = bottom - ((bottom >> 8) << 8);
        nudgebits |= (overX <= overY) ? 0x8 : 0x4;
      }
      if (tankBuildingCollision(sim, value, left, top, &bumptype, isFirstBump)) {
        WORLD overX = (((left >> 8) + 1) << 8) - 1 - left;
        WORLD overY = (((top >> 8) + 1) << 8) - 1 - top;
        nudgebits |= (overX <= overY) ? 0x8 : 0x1;
      }
    }

    if (nudgebits == 0) break;

    /* Apply nudges based on which edges were hit */
    if (nudgebits & 1) tankY = (tankY + 0x10) & 0xFFF0;
    if (nudgebits & 2) tankX = (tankX - 0x10) | 0x000F;
    if (nudgebits & 4) tankY = (tankY - 0x10) | 0x000F;
    if (nudgebits & 8) tankX = (tankX + 0x10) & 0xFFF0;

    /* Stuck check: opposing sides hit simultaneously */
    if (nudgebits == 5 || nudgebits == 10 || nudgebits == 15) break;

    isFirstBump = FALSE;
  }

  (*value)->x = tankX;
  (*value)->y = tankY;

  return bumptype;
#endif /* BOLO_LEGACY_SQUARE_COLLISION */
}

/*********************************************************
*NAME:          tankSpawnLoadout
*PURPOSE:
*  What a spawning tank is handed. The host is asked first,
*  so a scenario can arm a tank the game type would leave
*  empty; with nobody to ask, or nobody with an answer, the
*  sim's game type decides as it always has. Every place the
*  engine hands out a fresh loadout comes through here.
*
*ARGUMENTS:
*  sim       - The game the tank belongs to
*  playerNum - The slot being fuelled
*  shells    - Pointer to hold the number of shells
*  mines     - Pointer to hold the number of mines
*  armour    - Pointer to hold the amount of armour
*  trees     - Pointer to hold the number of trees
*********************************************************/
static void tankSpawnLoadout(GameSim *sim, BYTE playerNum, BYTE *shells,
                             BYTE *mines, BYTE *armour, BYTE *trees) {
  gameType loadoutType;
  if (gameSimSpawnLoadout(sim, playerNum, shells, mines, armour, trees) != FALSE) {
    return;
  }
  /* Nobody answered, so the game type decides. */
  loadoutType = sim->game;
  gameTypeGetItems(sim, &loadoutType, shells, mines, armour, trees);
}

/*********************************************************
*NAME:          tankCreate
*AUTHOR:        John Morrison
*CREATION DATE: 23/11/98
*LAST MODIFIED: 15/12/99
*PURPOSE:
*  Creates a new tank and sets its armour/mines etc. level
*  to the arguments. New tanks always start with full armour
*
*ARGUMENTS:
*  value  - Pointer to the tank structure
*  sts    - Pointer to player starts structure
*********************************************************/

void tankCreate(GameSim *sim, tank *value) {
  starts *sts = &sim->ss;
  BYTE minesAmount; /* Stuff the new tank is to start with */
  BYTE shellsAmount;
  BYTE armourAmount;
  BYTE treesAmount;
  /* Initialised because they are read whatever startsGetStart does with
     them; it writes all three unless there is no list to pick from, which is
     where a joining client asks before its map has arrived. */
  BYTE x = 0;    /* Things to pass to get the player start position */
  BYTE y = 0;
  TURNTYPE dir = (TURNTYPE)0;

  sim->tankShuttingDown = FALSE;

  New(*value);
  (*value)->x = 0;
  (*value)->y = 0;
  tankSpawnLoadout(sim, gameSimGetTankPlayer(sim, value), &shellsAmount,
                   &minesAmount, &armourAmount, &treesAmount);
  (*value)->armour = armourAmount;
  (*value)->destroyed = FALSE;
  (*value)->shells = shellsAmount;
  (*value)->mines = minesAmount;
  (*value)->trees = treesAmount;
  (*value)->onBoat = TRUE;
  (*value)->boatState = BoatState_InBoat;
  (*value)->lastBoatRiverX = 0;
  (*value)->lastBoatRiverY = 0;
  (*value)->leavingBoatTimer = 0;
  (*value)->leavingBoatAxis = 0;
  (*value)->showSight = FALSE;
  (*value)->sightLen = (BYTE) sim->rules.gunsight_max;
  (*value)->numKills = 0;
  (*value)->numDeaths = 0;
  (*value)->reload = 0;
  (*value)->speed = 0;
  (*value)->waterCount = 0;
  (*value)->deathWait = 0;
  (*value)->carryPills= NULL;
  (*value)->obstructed = FALSE;
  (*value)->newTank = TRUE;
  (*value)->autoSlowdown = FALSE;
  (*value)->autoHideGunsight = FALSE;
  (*value)->justFired = 0;
  (*value)->tankHitCount = 0;
  (*value)->firstLeft = 0;
  (*value)->firstRight = 0;
  (*value)->lastTankDeath = 0;
  (*value)->pendingDeathCause = DEATH_CAUSE_OTHER;
  (*value)->shellNearFrames = 0;
  /* Match numDeaths = 0 above: a fresh tank starts the round with an empty
   * cause tally so the two always add up. */
  {
    BYTE causeSlot = gameSimGetTankPlayer(sim, value);
    if (causeSlot < MAX_TANKS) {
      memset(sim->deathCauseCount[causeSlot], 0,
             sizeof(sim->deathCauseCount[causeSlot]));
    }
  }
  (*value)->bumpX = 0;
  (*value)->bumpY = 0;
  (*value)->bumpWait = 0;
  (*value)->residualSpeed = 0;
  /* The only place the modifiers are cleared. A respawn reuses the tank
     object and leaves them alone; the lobby return destroys every tank, so
     the next round's create is what puts a slot back to classic. */
  memset(&(*value)->mods, 0, sizeof((*value)->mods));

  /* Get the start position */
  sim->inStartFind = TRUE;
  startsGetStart(sim, sts, &x, &y, &dir, gameSimGetTankPlayer(sim, value));
  (*value)->x = x;
  (*value)->x <<= TANK_SHIFT_MAPSIZE;
  (*value)->x += MAP_SQUARE_MIDDLE;
  (*value)->y = y;
  (*value)->y <<= TANK_SHIFT_MAPSIZE;
  (*value)->y += MAP_SQUARE_MIDDLE;
  (*value)->angle = dir;
  sim->callbacks.centerTank(sim->callbacks.ctx);
  sim->inStartFind = FALSE;

  /* One report for every path that makes a tank — the round start, a join and
     a scripted spawn all land here. A tank coming back from a death does not:
     that reuses the object and is reported from tankDeath's server arm. */
  if (sim->isServer && sim->callbacks.tankSpawned) {
    sim->callbacks.tankSpawned(sim->callbacks.ctx,
                               gameSimGetTankPlayer(sim, value), x, y, false);
  }
}

/*********************************************************
*NAME:          tankDestroy
*AUTHOR:        John Morrison
*CREATION DATE: 23/11/98
*LAST MODIFIED: 20/6/00
*PURPOSE:
*  Destroys and frees the memory for the tank
*
*ARGUMENTS:
*  value - Pointer to the tank structure
*  mp    - Pointer to the map structure
*  pb    - Pointer to the pillbox structure
*  bs    - Pointer to the bases structure
*********************************************************/
void tankDestroy(GameSim *sim, tank *value) {
  bool isServer = sim->isServer;
  tankCarryPb q;

  sim->tankShuttingDown = TRUE;
  if ((*value) != NULL && isServer) {
    tankDropPills(sim, value);
  }
  sim->tankShuttingDown = FALSE;
  while ((*value) != NULL && !IsEmpty((*value)->carryPills)) {
    q = (*value)->carryPills;
    (*value)->carryPills = TankPillsTail(q);
    Dispose(q);
  }

  if ((*value) != NULL) {
    Dispose(*value);
  }
}


