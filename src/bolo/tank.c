/*********************************************************
 * tankBuildingCollision - Check if a WORLD coordinate
 * collides with a solid object (building, pillbox, base).
 * Sets bumptype flags for the type of collision.
 *********************************************************/
static bool tankBuildingCollision(GameSim *sim, tank *value, WORLD x, WORLD y,
                                  BumpInfo *bumptype, bool isFirstBump) {
  map *mp = &sim->mp;
  pillboxes *pb = &sim->pb;
  bases *bs = &sim->bs;
  BYTE mx = x >> TANK_SHIFT_MAPSIZE;
  BYTE my = y >> TANK_SHIFT_MAPSIZE;
  BYTE terrain = mapGetPos(mp, mx, my);

  if (terrain == BUILDING || terrain == HALFBUILDING) {
    *bumptype |= BumpInfo_SolidWall;
    return TRUE;
  }

  if (pillsExistPos(pb, mx, my) == TRUE) {
    BYTE armour = pillsGetArmourPos(pb, mx, my);
    if (armour != PILL_NOT_FOUND && armour > 0) {
      *bumptype |= BumpInfo_SolidWall;
      return TRUE;
    }
  }

  if (basesExistPos(bs, mx, my) == TRUE) {
    if (basesCantDrive(sim, mx, my, gameSimGetTankPlayer(sim, value)) == TRUE) {
      *bumptype |= BumpInfo_SolidWall;
      return TRUE;
    }
  }

  if (isFirstBump == TRUE && (*value)->boatState == BoatState_InBoat) {
    if (terrain == BOAT) {
      *bumptype |= BumpInfo_Boat;
    } else if (terrain != RIVER && terrain != DEEP_SEA) {
      *bumptype |= BumpInfo_Shore;
    }
  }

  return FALSE;
}

/*********************************************************
 * tankNudgeOtherTanks - Iteratively nudge this tank away
 * from all other living tanks that overlap.
 *********************************************************/
static void tankNudgeOtherTanks(GameSim *sim, tank *value) {
  BYTE myPlayer = gameSimGetTankPlayer(sim, value);
  BYTE t;

  for (t = 0; t < MAX_TANKS; t++) {
    if (t == myPlayer || sim->tanks[t] == NULL) continue;
    tank other = sim->tanks[t];
    if (other->armour > TANK_FULL_ARMOUR) continue;

    int j;
    for (j = 0; j < TANK_MAX_NUDGE_ITERATIONS; j++) {
      int dx = abs((*value)->x - other->x);
      int dy = abs((*value)->y - other->y);
      if (dx + dy >= TANK_COLLISION_DISTANCE) break;

      if (dx > TANK_NUDGE_THRESHOLD) {
        if ((*value)->x < other->x)
          (*value)->x = ((*value)->x - TANK_NUDGE_AMOUNT) | TANK_GRID_LOW_MASK;
        else
          (*value)->x = ((*value)->x + TANK_NUDGE_AMOUNT) & TANK_GRID_MASK;
      } else {
        if ((*value)->y < other->y)
          (*value)->y = ((*value)->y - TANK_NUDGE_AMOUNT) | TANK_GRID_LOW_MASK;
        else
          (*value)->y = ((*value)->y + TANK_NUDGE_AMOUNT) & TANK_GRID_MASK;
      }
    }
  }
}

/*********************************************************
 * tankNudgeBuildings - Iteratively nudge tank out of
 * building collisions using the direction-dependent
 * bounding box. Returns accumulated BumpInfo flags.
 *********************************************************/
static BumpInfo tankNudgeBuildings(GameSim *sim, tank *value, int maxNudges) {
  const TankBoundingBox *table = (*value)->onBoat ? tank_bbox_boat : tank_bbox_land;
  BYTE dirIndex = utilGetDir((*value)->angle);
  const TankBoundingBox *fc = &table[dirIndex];
  /* Convert margin-from-edge to distance-from-center:
   * For a 16px sprite, center is at pixel 8.
   * distance_from_center = (8 - margin) pixels, then scale to WORLD units (<< 4) */
  WORLD topInset    = (8 - fc->top)    << 4;
  WORLD bottomInset = (8 - fc->bottom) << 4;
  WORLD leftInset   = (8 - fc->left)   << 4;
  WORLD rightInset  = (8 - fc->right)  << 4;
  BumpInfo bumptype = BumpInfo_None;
  bool isFirstBump = TRUE;
  int i;

  WORLD tankX = (*value)->x;
  WORLD tankY = (*value)->y;

  for (i = 0; i < maxNudges; i++) {
    WORLD top    = tankY - topInset;
    WORLD bottom = tankY + bottomInset;
    WORLD left   = tankX - leftInset;
    WORLD right  = tankX + rightInset;
    BYTE nudgebits = 0;

    /* Check 4 orthogonal edge midpoints */
    if (tankBuildingCollision(sim, value, tankX, top, &bumptype, isFirstBump))
      nudgebits |= 1;
    if (tankBuildingCollision(sim, value, right, tankY, &bumptype, isFirstBump))
      nudgebits |= 2;
    if (tankBuildingCollision(sim, value, tankX, bottom, &bumptype, isFirstBump))
      nudgebits |= 4;
    if (tankBuildingCollision(sim, value, left, tankY, &bumptype, isFirstBump))
      nudgebits |= 8;

    /* If no orthogonal collision, check 4 diagonal corners.
     * Only nudge on the axis with less penetration so the
     * tank slides along the wall instead of getting stuck. */
    if (nudgebits == 0) {
      if (tankBuildingCollision(sim, value, right, top, &bumptype, isFirstBump)) {
        WORLD overX = right - ((right >> 8) << 8);       /* penetration into tile from left edge */
        WORLD overY = (((top >> 8) + 1) << 8) - 1 - top; /* penetration into tile from bottom edge */
        nudgebits |= (overX <= overY) ? 0x2 : 0x1;
      }
      if (tankBuildingCollision(sim, value, right, bottom, &bumptype, isFirstBump)) {
        WORLD overX = right - ((right >> 8) << 8);
        WORLD overY = bottom - ((bottom >> 8) << 8);
        nudgebits |= (overX <= overY) ? 0x2 : 0x4;
      }
      if (tankBuildingCollision(sim, value, left, bottom, &bumptype, isFirstBump)) {
        WORLD overX = (((left >> 8) + 1) << 8) - 1 - left;
        WORLD overY = bottom - ((bottom >> 8) << 8);
        nudgebits |= (overX <= overY) ? 0x8 : 0x4;
      }
      if (tankBuildingCollision(sim, value, left, top, &bumptype, isFirstBump)) {
        WORLD overX = (((left >> 8) + 1) << 8) - 1 - left;
        WORLD overY = (((top >> 8) + 1) << 8) - 1 - top;
        nudgebits |= (overX <= overY) ? 0x8 : 0x1;
      }
    }

    if (nudgebits == 0) break;

    /* Apply nudges based on which edges were hit */
    if (nudgebits & 1) tankY = (tankY + 0x10) & 0xFFF0;
    if (nudgebits & 2) tankX = (tankX - 0x10) | 0x000F;
    if (nudgebits & 4) tankY = (tankY - 0x10) | 0x000F;
    if (nudgebits & 8) tankX = (tankX + 0x10) & 0xFFF0;

    /* Stuck check: opposing sides hit simultaneously */
    if (nudgebits == 5 || nudgebits == 10 || nudgebits == 15) break;

    isFirstBump = FALSE;
  }

  (*value)->x = tankX;
  (*value)->y = tankY;

  return bumptype;
}

/*********************************************************
*NAME:          tankCreate
*AUTHOR:        John Morrison
*CREATION DATE: 23/11/98
*LAST MODIFIED: 15/12/99
*PURPOSE:
*  Creates a new tank and sets its armour/mines etc. level
*  to the arguments. New tanks always start with full armour
*
*ARGUMENTS:
*  value  - Pointer to the tank structure
*  sts    - Pointer to player starts structure
*********************************************************/
void tankCreate(GameSim *sim, tank *value) {
  starts *sts = &sim->ss;
  BYTE minesAmount; /* Stuff the new tank is to start with */
  BYTE shellsAmount;
  BYTE armourAmount;
  BYTE treesAmount;
  BYTE x;    /* Things to pass to get the player start position */
  BYTE y;
  TURNTYPE dir;

  sim->tankShuttingDown = FALSE;

  New(*value);
  (*value)->x = 0;
  (*value)->y = 0;
  gameTypeGetItems(sim, &sim->game, &shellsAmount, &minesAmount, &armourAmount, &treesAmount);
  (*value)->armour = armourAmount;
  (*value)->shells = shellsAmount;
  (*value)->mines = minesAmount;
  (*value)->trees = treesAmount;
  (*value)->onBoat = TRUE;
  (*value)->boatState = BoatState_InBoat;
  (*value)->lastBoatRiverX = 0;
  (*value)->lastBoatRiverY = 0;
  (*value)->leavingBoatTimer = 0;
  (*value)->showSight = FALSE;
  (*value)->sightLen = GUNSIGHT_MAX;
  (*value)->numKills = 0;
  (*value)->numDeaths = 0;
  (*value)->reload = 0;
  (*value)->speed = 0;
  (*value)->waterCount = 0;
  (*value)->deathWait = 0;
  (*value)->carryPills= NULL;
  (*value)->obstructed = FALSE;
  (*value)->newTank = TRUE;
  (*value)->autoSlowdown = FALSE;
  (*value)->autoHideGunsight = FALSE;
  (*value)->justFired = FALSE;
  (*value)->tankHitCount = 0;
  (*value)->firstLeft = 0;
  (*value)->firstRight = 0;
  (*value)->lastTankDeath = 0;
  (*value)->bumpX = 0;
  (*value)->bumpY = 0;
  (*value)->residualSpeed = 0;

  /* Get the start position */
  sim->inStartFind = TRUE;
  startsGetStart(sim, sts, &x, &y, &dir, gameSimGetTankPlayer(sim, value));
  (*value)->x = x;
  (*value)->x <<= TANK_SHIFT_MAPSIZE;
  (*value)->x += MAP_SQUARE_MIDDLE;
  (*value)->y = y;
  (*value)->y <<= TANK_SHIFT_MAPSIZE;
  (*value)->y += MAP_SQUARE_MIDDLE;
  (*value)->angle = dir;
  sim->callbacks.centerTank(sim->callbacks.ctx);
  sim->inStartFind = FALSE;
}

/*********************************************************
*NAME:          tankDestroy
*AUTHOR:        John Morrison
*CREATION DATE: 23/11/98
*LAST MODIFIED: 20/6/00
*PURPOSE:
*  Destroys and frees the memory for the tank
*
*ARGUMENTS:
*  value - Pointer to the tank structure
*  mp    - Pointer to the map structure
*  pb    - Pointer to the pillbox structure
*  bs    - Pointer to the bases structure
*********************************************************/
void tankDestroy(GameSim *sim, tank *value) {
  bool isServer = sim->isServer;
  tankCarryPb q;

  sim->tankShuttingDown = TRUE;
  if ((*value) != NULL && isServer) {
    tankDropPills(sim, value);
  }
  sim->tankShuttingDown = FALSE;
  while ((*value) != NULL && !IsEmpty((*value)->carryPills)) {
    q = (*value)->carryPills;
    (*value)->carryPills = TankPillsTail(q);
    Dispose(q);
  }

  if ((*value) != NULL) {
    Dispose(*value);
  }
}


