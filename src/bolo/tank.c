/*********************************************************
*NAME:          tankDeath
*AUTHOR:        John Morrison
*CREATION DATE: 7/1/99
*LAST MODIFIED: 9/1/00
*PURPOSE:
*  The tank has died. Reinit its location and increment
*  the death count
*
*ARGUMENTS:
*  value - Pointer to the tank structure
*  sts   - Pointer to the starts structure
*********************************************************/
void tankDeath(GameSim *sim, tank *value) {
  starts *sts = &sim->ss;
  bool isServer = sim->isServer;
  BYTE shellAmount; /* Stuff the new tank is to start with */
  BYTE minesAmount;
  BYTE armourAmount;
  BYTE treesAmount;
  /* Initialised because they are read whatever startsGetStart does with
     them; it writes all three unless there is no list to pick from. */
  BYTE x = 0;   /* New location of the tank */
  BYTE y = 0;
  TURNTYPE dir = (TURNTYPE)0;

  /* Client path (legacy single-player or networked client) */
  if (!isServer) {
    logAddEvent(log_PlayerLocation, gameSimGetTankPlayer(sim, value), 0, 0, 0, 0, NULL);
    lgmTankDied(&sim->lgmen[gameSimGetTankPlayer(sim, value)]);
	/* Playing on a client */
    if (!isServer) {
        /* Server-authoritative: server sim handles respawn for both local
         * and UDP transport.  The client just marks inStartFind so the
         * death/respawn transition is tracked; the server picks the new
         * start position and sends it in the next snapshot. */
        if (sim->inStartFind == FALSE) {
          sim->inStartFind = TRUE;
        }
      }
    (*value)->onBoat = TRUE;
    (*value)->boatState = BoatState_InBoat;
    (*value)->numDeaths++;
    (*value)->reload = 0;
    (*value)->speed = 0;
    (*value)->bumpX = 0;
    (*value)->bumpY = 0;
    (*value)->bumpWait = 0;
    (*value)->residualSpeed = 0;
    (*value)->waterCount = 0;
    /* Get the start position */
    if (!isServer) {
      frontEndKillsDeaths(clientSimFromSim(sim), (*value)->numKills, (*value)->numDeaths);
    }
  } else if (isServer) {
    /* Server-authoritative respawn: pick a new start and reset resources.
     * tankSpawnLoadout, not sim->game: this is the path that would hand a
     * slot carrying an open-mode loadout override a TOURNAMENT (empty)
     * loadout on every death — first life armed, every respawn with
     * zero shells. */
    lgmTankDied(&sim->lgmen[gameSimGetTankPlayer(sim, value)]);
    tankSpawnLoadout(sim, gameSimGetTankPlayer(sim, value), &shellAmount,
                     &minesAmount, &armourAmount, &treesAmount);
    (*value)->armour = armourAmount;
    (*value)->destroyed = FALSE;
    (*value)->tankHitCount = 0;
    (*value)->shells = shellAmount;
    (*value)->mines = minesAmount;
    (*value)->trees = treesAmount;
    sim->inStartFind = TRUE;
    startsGetStart(sim, sts, &x, &y, &dir, gameSimGetTankPlayer(sim, value));
    (*value)->x = x;
    (*value)->x <<= TANK_SHIFT_MAPSIZE;
    (*value)->x += MAP_SQUARE_MIDDLE;
    (*value)->y = y;
    (*value)->y <<= TANK_SHIFT_MAPSIZE;
    (*value)->y += MAP_SQUARE_MIDDLE;
    (*value)->angle = dir;
    sim->inStartFind = FALSE;
    (*value)->onBoat = TRUE;
    (*value)->boatState = BoatState_InBoat;
    (*value)->newTank = TRUE;
    (*value)->numDeaths++;
    /* Tally the cause alongside the death itself, so the per-cause counts
     * always sum to numDeaths. Read-and-clear: an untagged death (no damage
     * site claimed it) lands in DEATH_CAUSE_OTHER rather than repeating the
     * previous life's cause. Observation only — no sim state reads this. */
    {
      BYTE causeSlot = gameSimGetTankPlayer(sim, value);
      BYTE causeTag = (*value)->pendingDeathCause;
      if (causeTag >= DEATH_CAUSE_NUM) {
        causeTag = DEATH_CAUSE_OTHER;
      }
      if (causeSlot < MAX_TANKS) {
        sim->deathCauseCount[causeSlot][causeTag]++;
      }
      (*value)->pendingDeathCause = DEATH_CAUSE_OTHER;
    }
    /* Fresh life, fresh near-shell memory: "a shell was near me in the last
     * second" must mean this life, not the one that just ended. */
    (*value)->shellNearFrames = 0;
    (*value)->reload = 0;
    (*value)->speed = 0;
    (*value)->bumpX = 0;
    (*value)->bumpY = 0;
    (*value)->bumpWait = 0;
    (*value)->residualSpeed = 0;
    (*value)->waterCount = 0;
    if (sim->isTutorial && sim->tutorialStartIdx == 1) {
      sim->tutorialRespawn1Pending = TRUE;
    }
    /* The square is the start just chosen, not the one the tank died on. */
    if (sim->callbacks.tankSpawned) {
      sim->callbacks.tankSpawned(sim->callbacks.ctx,
                                 gameSimGetTankPlayer(sim, value), x, y, true);
    }
  }
}



