#!/usr/bin/env python3
"""
Each player's client runs a Bot Host of its own (src/bothost/bothost_embed.h),
and the server spreads its bots over those hosts and itself.

WHAT RUNS
    One WinBoloDS (-maprotate, -bots N, the default brain) and WinBoloHeadless
    players that join it on 127.0.0.1. No GUI program runs. The DS is stopped
    with its console "quit" on stdin, never with a signal.

    Timeline (wall clock, from the DS start):
      0 s     P1 and P2 join, each with --bothost-slots SLOTS.
      ~25 s   P1 ends by itself (--ticks): a normal leave.
      ~35 s   P1 joins again (a new process, the same name): the rejoin.
      ~50 s   P2 vanishes (--vanish-at-tick): no quit from the player or its
              host, as in a crash. The DS times both out.
      ROUND   The round ends (a scenario script calls end_round). In
              -maprotate mode the DS disconnects every player at the round
              end (serverLifecycleRotateRound), so each host stops with its
              player. P1 then joins the next round again.

CHECKS (one PASS/FAIL line each)
    1. join:     both players' hosts connect, and bots think on each of them.
    2. leave:    when P1 leaves, every bot on P1's host comes back to the
                 server, and the game state does not change at that tick
                 (snapshot before and after: the same bots, names, kills,
                 deaths, positions within 2 tiles, pill and base owners).
    3. rejoin:   P1's host connects again and takes bots again; no duplicate
                 or lost bot (the snapshot shows each bot name once, all N
                 there), and no seat stays offered with no answer.
    4. crash:    P2's bots come back after P2 vanishes, with the same state
                 check as 2.
    5. round:    at the round end every host goes and every bot comes back
                 to the server; in the next round P1 joins again, its host
                 takes bots again, and each bot name is there once.
    6. cpu:      the DS logs a CPU estimate (the percent each machine sends
                 for the lobby's Bot Host rows) for P1's host, P2's host and
                 the server itself, and each is a percent ("N%" or "<1%").

    7. optout:   a second run with its own DS (--case optout runs only
                 it). P1 joins and at its tick OPTOUT_TICK turns on the
                 lobby's "Don't run bots on this computer for this game"
                 (--bothost-optout-at-tick). Its host offers 0 slots, every
                 bot on it comes back to the server at once with the same
                 state check as 2, and the host stays connected. No bot
                 thinks on P1 while the opt-out is on. At OPTIN_TICK P1
                 turns it off (--bothost-optin-at-tick): the host offers
                 its slots again and takes bots again.

    Brain (Lua) state does not move with a bot: the bot gets a new brain on
    each move, as with any Bot Host fallback. The test does not check it.

Usage: python tests/client_bot_hosts_test.py [--build DIR] [--port N]
           [--out DIR] [--bots N] [--slots N] [--case all|hosts|optout]
Exit 0 when every check passes. The logs stay in --out (default: a folder
client_bot_hosts_<time> under the system temp folder).
"""
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import time
from pathlib import Path

try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
except (AttributeError, ValueError):        # pragma: no cover
    pass

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
SRC_MAP = REPO / "data" / "maps" / "Everard Island.map"

ROUND_TICKS = 9000          # about 90 s of wall clock in the first round
SNAP_INTERVAL = 5

SCRIPT = """\
-- GENERATED by tests/client_bot_hosts_test.py: end the first round after a
-- fixed number of ticks so -maprotate starts the next one.
scenario = {
  name        = "client_bot_hosts_test",
  description = "Ends the first round after a fixed number of ticks.",
  api         = 1,
}

local ROUND_TICKS = %d
local ended = false
function on_tick(t)
  if not ended and t >= ROUND_TICKS then
    ended = true
    game.end_round("client_bot_hosts_test: round over")
  end
end
"""

OFFER_RE = re.compile(r'\[bothost\] bot (\d+) "([^"]*)" offered to Bot Host "([^"]*)"')
THINK_RE = re.compile(r'\[bothost\] bot (\d+) "([^"]*)" now thinks on Bot Host '
                      r'"([^"]*)" \(game tick (\d+)\)')
BACK_RE = re.compile(r'\[bothost\] bot (\d+) "([^"]*)" back in-process from Bot '
                     r'Host "([^"]*)" \((.*), game tick (\d+)\)')
HOST_UP_RE = re.compile(r'\[bothost\] player (\d+) "([^"]*)" Bot Host connected '
                        r'from \S+ with (\d+) slots')
CPU_RE = re.compile(r'\[bothost\] CPU estimate: (Bot Host|the server) "([^"]*)" '
                    r"(\d+%|<1%) of its machine's CPU, (\d+) bots")
HOST_GONE_RE = re.compile(r'\[bothost\] Bot Host "([^"]*)" at \S+ gone \((.*)\)')
SLOTS_RE = re.compile(r'\[bothost\] Bot Host "([^"]*)" now offers this server '
                      r'(\d+) slots')

# The opt-out case: P1's own ticks at which it turns the opt-out on and off,
# and when it ends.
OPTOUT_TICK = 1500
OPTIN_TICK = 2500
OPTOUT_END_TICK = 3500


def find_exe(build_dir, name):
    for c in (build_dir / (name + ".exe"), build_dir / name,
              build_dir / "Release" / (name + ".exe")):
        if c.exists():
            return c
    return None


class Run:
    def __init__(self, build_dir, out_dir, port, bots, slots):
        self.build = build_dir
        self.out = out_dir
        self.port = port
        self.bots = bots
        self.slots = slots
        self.ds = None
        self.ds_log = out_dir / "ds_stderr.txt"
        self.players = []
        self.t0 = time.time()

    def ds_text(self):
        try:
            return self.ds_log.read_text(encoding="utf-8", errors="replace")
        except OSError:
            return ""

    def start_ds(self, ds_exe, mapdir):
        logdir = self.out / "ds_logs"
        logdir.mkdir(exist_ok=True)
        cmd = [str(ds_exe), "-mapdir", str(mapdir), "-maprotate",
               "-port", str(self.port), "-gametype", "open",
               "-bots", str(self.bots), "-ai", "yes", "-seed", "11",
               "-notracker", "-nowinbolonet", "-threads", "12",
               "-noemptyreset",
               # The test needs bots on the players' hosts: the even spread
               # puts them there even while the server has room.
               "-bothost-spread-even",
               # Every bot of a host that goes comes back to the server,
               # past its slots (checks 2, 4, 5 and 7): the old fall-back.
               "-bothost-enforce-server-limit", "0",
               "-snapjson", str(self.out / "snap.jsonl"),
               "-snapinterval", str(SNAP_INTERVAL),
               "-log", str(logdir)]
        (self.out / "ds_cmd.txt").write_text(" ".join(cmd), encoding="utf-8")
        self.ds_err = open(self.ds_log, "wb")
        self.ds = subprocess.Popen(cmd, cwd=str(self.build),
                                   stdin=subprocess.PIPE,
                                   stdout=self.ds_err, stderr=subprocess.STDOUT)

    def start_player(self, hl_exe, label, name, extra):
        log = self.out / ("%s.txt" % label)
        cache = self.out / ("cache_%s" % name)
        cmd = [str(hl_exe), "--server", "127.0.0.1", "--port", str(self.port),
               "--name", name, "--ai", "no",
               "--bothost-slots", str(self.slots),
               "--bothost-cache", str(cache)] + extra
        f = open(log, "wb")
        p = subprocess.Popen(cmd, cwd=str(self.build), stdin=subprocess.DEVNULL,
                             stdout=f, stderr=subprocess.STDOUT)
        self.players.append((label, p, f, log))
        print("  %5.1f s: %s joins as \"%s\" (%s)" % (time.time() - self.t0,
                                                     label, name, " ".join(extra)))
        return p

    def wait_for(self, what, pred, timeout):
        end = time.time() + timeout
        while time.time() < end:
            if pred():
                return True
            if self.ds.poll() is not None:
                print("  the DS ended early (exit %s)" % self.ds.returncode)
                return False
            time.sleep(0.5)
        print("  timed out waiting for %s" % what)
        return False

    def quit_ds(self):
        if self.ds is None:
            return
        if self.ds.poll() is None:
            try:
                self.ds.stdin.write(b"quit\n")
                self.ds.stdin.flush()
            except OSError:
                pass
            try:
                self.ds.wait(timeout=30)
            except subprocess.TimeoutExpired:
                print("  NOTE: the DS did not end 30 s after quit; left running")
        for label, p, f, log in self.players:
            try:
                p.wait(timeout=20)
            except subprocess.TimeoutExpired:
                print("  NOTE: %s did not end after the DS quit; left running" % label)
            f.close()
        self.ds_err.close()


def events(text):
    """The [bothost] events in order: (kind, groups)."""
    out = []
    for line in text.splitlines():
        for kind, rx in (("offer", OFFER_RE), ("think", THINK_RE),
                         ("back", BACK_RE), ("up", HOST_UP_RE),
                         ("gone", HOST_GONE_RE), ("slots", SLOTS_RE)):
            m = rx.search(line)
            if m:
                out.append((kind, m.groups()))
                break
    return out


def thinks_on(text, host):
    return [g for k, g in events(text) if k == "think" and g[2] == host]


def locations(text):
    """Where each bot's brain runs after the events so far: a host name,
    "offered to <host>", or "server"."""
    where = {}
    for k, g in events(text):
        if k == "offer":
            where[int(g[0])] = "offered to " + g[2]
        elif k == "think":
            where[int(g[0])] = g[2]
        elif k == "back":
            where[int(g[0])] = "server"
    return where


def load_snaps(path):
    snaps = []
    try:
        with open(path, encoding="utf-8", errors="replace") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                try:
                    snaps.append(json.loads(line))
                except ValueError:
                    pass
    except OSError:
        pass
    return snaps


def same_state(snaps, tick, bot):
    """Compare the snapshot at or before tick with the next one after it.
    Returns (ok, why)."""
    before = after = None
    for i, s in enumerate(snaps):
        if s.get("reason") != "snapshot":
            continue
        if s["tick"] <= tick:
            before = s
            if i + 1 < len(snaps) and snaps[i + 1].get("reason") == "snapshot" \
                    and snaps[i + 1]["tick"] > tick:
                after = snaps[i + 1]
                break
    if before is None or after is None:
        return False, "no snapshots around game tick %d" % tick
    if after["tick"] - before["tick"] > 2 * SNAP_INTERVAL:
        return False, "snapshots %d and %d are too far apart" % (before["tick"], after["tick"])
    tb = {t["player"]: t for t in before["tanks"]}
    ta = {t["player"]: t for t in after["tanks"]}
    # The player who left drops out of the snapshots at the same time, so
    # only the bot that moved is compared.
    b, a = tb.get(bot), ta.get(bot)
    if b is None or a is None:
        return False, "bot %d is not in the snapshots" % bot
    if b["name"] != a["name"]:
        return False, "bot %d name %r became %r" % (bot, b["name"], a["name"])
    if a["kills"] < b["kills"] or a["deaths"] < b["deaths"]:
        return False, "bot %d kills or deaths went down" % bot
    if b.get("alive") and a.get("alive") and "x" in b and "x" in a:
        d = max(abs(a["x"] - b["x"]), abs(a["y"] - b["y"]))
        if d > 2.0:
            return False, "bot %d jumped %.1f tiles" % (bot, d)
    lost = [i for i, (pb, pa) in enumerate(zip(before["pillboxes"], after["pillboxes"]))
            if pb["owner"] == bot and pa["owner"] != bot and not pb.get("in_tank")]
    if lost:
        return False, "bot %d lost pills %s at the move" % (bot, lost)
    lostb = [i for i, (bb, ba) in enumerate(zip(before["bases"], after["bases"]))
             if bb["owner"] == bot and ba["owner"] != bot]
    if lostb:
        return False, "bot %d lost bases %s at the move" % (bot, lostb)
    return True, "ticks %d..%d the same" % (before["tick"], after["tick"])


def check_moves(snaps, backs, label):
    ok = True
    for g in backs:
        bot, name, host, why, tick = int(g[0]), g[1], g[2], g[3], int(g[4])
        good, why2 = same_state(snaps, tick, bot)
        print("    bot %d \"%s\" back from \"%s\" (%s) at game tick %d: %s" %
              (bot, name, host, why, tick, why2))
        ok = ok and good
    if not backs:
        print("    no bot came back from %s" % label)
        ok = False
    return ok


def run_optout(build_dir, out_dir, port, bots, slots, ds_exe, hl_exe, mapdir):
    """7. optout: P1 turns its computer's bots off for this game, then on
    again. Returns True when every part holds."""
    out_dir.mkdir(parents=True, exist_ok=True)
    print("=== opt-out: %d bots, P1 offers %d slots, port %d" % (bots, slots, port))
    print("    logs: %s" % out_dir)
    run = Run(build_dir, out_dir, port, bots, slots)
    ok = False
    try:
        run.start_ds(ds_exe, mapdir)
        if not run.wait_for("the DS to start its bots",
                            lambda: "[bothost]" in run.ds_text(), 20):
            return False
        run.start_player(hl_exe, "p1opt", "P1",
                         ["--bothost-optout-at-tick", str(OPTOUT_TICK),
                          "--bothost-optin-at-tick", str(OPTIN_TICK),
                          "--ticks", str(OPTOUT_END_TICK)])
        p1 = run.players[0][1]
        try:
            p1.wait(timeout=OPTOUT_END_TICK / 50 + 90)
        except subprocess.TimeoutExpired:
            print("  P1 did not end by itself")
        time.sleep(3)
        p1_log = run.players[0][3]
        try:
            p1_text = p1_log.read_text(encoding="utf-8", errors="replace")
        except OSError:
            p1_text = ""
        ev = events(run.ds_text())

        # Where the 0-slot report and the report of the slots again are.
        i_zero = next((i for i, (k, g) in enumerate(ev)
                       if k == "slots" and g[0] == "P1" and g[1] == "0"), -1)
        i_again = next((i for i, (k, g) in enumerate(ev)
                        if i > i_zero >= 0 and k == "slots" and g[0] == "P1"
                        and g[1] != "0"), -1)
        before = [g for k, g in ev[:max(i_zero, 0)]
                  if k == "think" and g[2] == "P1"]
        print("  P1 turned the opt-out on: %s; off again: %s" %
              ("yes" if "Turning this computer's bots off" in p1_text else "no",
               "yes" if "Turning this computer's bots on again" in p1_text else "no"))
        print("  bots that thought on P1 before the opt-out: %d" % len(before))
        print("  DS: P1 offers 0 slots: %s; offers slots again: %s" %
              ("yes" if i_zero >= 0 else "no",
               ("yes (%s)" % ev[i_again][1][1]) if i_again >= 0 else "no"))

        # Every bot on P1 at the 0-slot report comes back at once, for that
        # reason; the host stays connected until P1 itself ends.
        on_p1 = set()
        for k, g in ev[:max(i_zero, 0)]:
            if k == "think" and g[2] == "P1":
                on_p1.add(g[0])
            elif k == "back" and g[2] == "P1":
                on_p1.discard(g[0])
        window = ev[i_zero + 1:i_again] if i_zero >= 0 and i_again >= 0 else []
        backs = [g for k, g in ev[i_zero + 1:] if k == "back" and g[2] == "P1"
                 and "offers 0 slots" in g[3]] if i_zero >= 0 else []
        back_ids = {g[0] for g in backs}
        gone_early = [g for k, g in window if k == "gone" and g[0] == "P1"]
        thinks_in = [g for k, g in window if k == "think" and g[2] == "P1"]
        offers_in = [g for k, g in window if k == "offer" and g[2] == "P1"]
        after = [g for k, g in ev[i_again + 1:] if k == "think" and g[2] == "P1"]             if i_again >= 0 else []
        print("  bots on P1 at the opt-out: %s; came back for it: %s" %
              (sorted(on_p1), sorted(back_ids)))
        print("  while it was on: host gone %d, offers to P1 %d, thinks on P1 %d" %
              (len(gone_early), len(offers_in), len(thinks_in)))
        print("  bots that thought on P1 after it was off again: %d" % len(after))
        snaps = load_snaps(out_dir / "snap.jsonl")
        moves_ok = check_moves(snaps, backs, "P1's opt-out")
        ok = (i_zero >= 0 and i_again >= 0 and bool(before) and
              bool(on_p1) and on_p1 <= back_ids and not gone_early and
              not offers_in and not thinks_in and bool(after) and moves_ok)
    finally:
        run.quit_ds()
    return ok


def main():
    args = sys.argv[1:]
    build_dir = REPO / "build"
    port = 50171
    bots = 6
    slots = 3
    out_dir = None
    case = "all"
    i = 0
    while i < len(args):
        a = args[i]
        if a == "--build" and i + 1 < len(args):
            build_dir = Path(args[i + 1]); i += 2
        elif a == "--port" and i + 1 < len(args):
            port = int(args[i + 1]); i += 2
        elif a == "--out" and i + 1 < len(args):
            out_dir = Path(args[i + 1]); i += 2
        elif a == "--bots" and i + 1 < len(args):
            bots = int(args[i + 1]); i += 2
        elif a == "--slots" and i + 1 < len(args):
            slots = int(args[i + 1]); i += 2
        elif a == "--case" and i + 1 < len(args) and \
                args[i + 1] in ("all", "hosts", "optout"):
            case = args[i + 1]; i += 2
        else:
            print("unknown argument %s" % a)
            return 2
    if out_dir is None:
        out_dir = Path(tempfile.gettempdir()) / time.strftime("client_bot_hosts_%Y%m%d_%H%M%S")
    out_dir.mkdir(parents=True, exist_ok=True)
    print("=== client Bot Hosts: %d bots, players offer %d slots each, port %d" %
          (bots, slots, port))
    print("    logs: %s" % out_dir)

    ds_exe = find_exe(build_dir, "WinBoloDS")
    hl_exe = find_exe(build_dir, "WinBoloHeadless")
    if not ds_exe or not hl_exe:
        print("FAIL: WinBoloDS or WinBoloHeadless not found under %s" % build_dir)
        return 1
    mapdir = out_dir / "mapdir"
    mapdir.mkdir(exist_ok=True)
    shutil.copyfile(SRC_MAP, mapdir / "client_bot_hosts.map")
    (mapdir / "client_bot_hosts.scenario.lua").write_text(SCRIPT % ROUND_TICKS,
                                                         encoding="utf-8")

    if case == "optout":
        ok = run_optout(build_dir, out_dir / "optout", port, bots, slots,
                        ds_exe, hl_exe, mapdir)
        print()
        print("%s: optout" % ("PASS" if ok else "FAIL"))
        print("logs: %s" % out_dir)
        return 0 if ok else 1

    run = Run(build_dir, out_dir, port, bots, slots)
    results = []
    try:
        run.start_ds(ds_exe, mapdir)
        if not run.wait_for("the DS to start its bots",
                            lambda: "[bothost]" in run.ds_text(), 20):
            results.append(("join", False))
            return 1
        # 1. join
        run.start_player(hl_exe, "p1a", "P1", ["--ticks", "1000"])
        run.start_player(hl_exe, "p2", "P2", ["--vanish-at-tick", "2300"])
        ok = run.wait_for("bots on both hosts",
                          lambda: thinks_on(run.ds_text(), "P1") and
                          thinks_on(run.ds_text(), "P2"), 40)
        t = run.ds_text()
        ups = [g for k, g in events(t) if k == "up"]
        print("  hosts up: %s" % ", ".join('"%s" %s slots' % (g[1], g[2]) for g in ups))
        print("  bots on P1: %d, on P2: %d" % (len(thinks_on(t, "P1")),
                                              len(thinks_on(t, "P2"))))
        results.append(("join", bool(ok)))

        # 6. cpu: each host and the server send a percent for their rows
        def cpu_rows():
            return [m.groups() for m in CPU_RE.finditer(run.ds_text())]
        ok = run.wait_for("a CPU estimate for P1, P2 and the server",
                          lambda: {("Bot Host", "P1"), ("Bot Host", "P2")} <=
                          {(g[0], g[1]) for g in cpu_rows()} and
                          any(g[0] == "the server" for g in cpu_rows()), 20)
        for g in cpu_rows():
            print("  CPU estimate: %s \"%s\" %s (%s bots)" % g)
        results.append(("cpu", bool(ok)))

        # 2. leave: P1 ends by itself after 1000 of its own ticks
        p1a = run.players[0][1]
        try:
            p1a.wait(timeout=60)
        except subprocess.TimeoutExpired:
            print("  P1 did not end by itself")
        time.sleep(3)
        t = run.ds_text()
        ev = events(t)
        backs = [g for k, g in ev if k == "back" and g[2] == "P1"]
        gone = [g for k, g in ev if k == "gone" and g[0] == "P1"]
        print("  P1 left at %.1f s; its host gone: %s" %
              (time.time() - run.t0, "; ".join(g[1] for g in gone) or "no"))
        snaps = load_snaps(out_dir / "snap.jsonl")
        results.append(("leave", check_moves(snaps, backs, "P1") and bool(gone)))

        # 3. rejoin
        n_before = len(thinks_on(t, "P1"))
        run.start_player(hl_exe, "p1b", "P1", [])
        ok = run.wait_for("bots on P1's host again",
                          lambda: len(thinks_on(run.ds_text(), "P1")) > n_before, 40)
        time.sleep(5)
        snaps = load_snaps(out_dir / "snap.jsonl")
        last = [s for s in snaps if s.get("reason") == "snapshot"][-1:]
        dup_ok = False
        if last:
            names = [tk["name"] for tk in last[0]["tanks"]]
            bot_names = [n for n in names if n not in ("P1", "P2")]
            dup_ok = len(bot_names) == bots and len(set(bot_names)) == bots
            print("  players after the rejoin (tick %d): %s" % (last[0]["tick"], names))
        # no seat stays offered with no answer: each offer is followed by a
        # think or a back for that bot
        pending = {}
        for k, g in events(run.ds_text()):
            if k == "offer":
                pending[g[0]] = g[2]
            elif k in ("think", "back"):
                pending.pop(g[0], None)
        if pending:
            print("  seats still offered with no answer: %s" % pending)
        results.append(("rejoin", bool(ok) and dup_ok and not pending))

        # 4. crash: P2 vanishes at its tick 2300
        p2 = run.players[1][1]
        try:
            p2.wait(timeout=90)
        except subprocess.TimeoutExpired:
            print("  P2 did not vanish")
        vanish_t = time.time()
        run.wait_for("P2's host to time out",
                     lambda: any(k == "gone" and g[0] == "P2"
                                 for k, g in events(run.ds_text())), 20)
        time.sleep(2)
        ev = events(run.ds_text())
        gone = [g for k, g in ev if k == "gone" and g[0] == "P2"]
        backs = [g for k, g in ev if k == "back" and g[2] == "P2"]
        print("  P2 vanished (exit %s); its host gone %.1f s later: %s" %
              (p2.returncode, time.time() - vanish_t,
               "; ".join(g[1] for g in gone) or "no"))
        snaps = load_snaps(out_dir / "snap.jsonl")
        results.append(("crash", check_moves(snaps, backs, "P2") and bool(gone)))

        # 5. round: wait for the next round, then P1 joins it again
        ok = run.wait_for("the next round",
                          lambda: "Map rotation: started new round." in run.ds_text(),
                          ROUND_TICKS / 50 + 60)
        t = run.ds_text()
        cut = t.find("Map rotation: started new round.")
        where_end = locations(t[:cut]) if cut >= 0 else {}
        all_back = bool(where_end) and all(h == "server" for h in where_end.values())
        p1b = run.players[2][1]
        try:
            p1b.wait(timeout=20)
        except subprocess.TimeoutExpired:
            print("  P1 was not disconnected at the round end")
        print("  round end: P1's second process exit %s; where every bot is: %s" %
              (p1b.returncode, where_end))
        ok2 = False
        dup_ok = False
        if ok:
            print("  the next round started at %.1f s" % (time.time() - run.t0))
            run.start_player(hl_exe, "p1c", "P1", [])
            ok2 = run.wait_for("bots on P1's host in the next round",
                               lambda: thinks_on(run.ds_text()[cut:], "P1"), 40)
            time.sleep(5)
            snaps = load_snaps(out_dir / "snap.jsonl")
            last = [s for s in snaps if s.get("reason") == "snapshot"][-1:]
            if last:
                names = [tk["name"] for tk in last[0]["tanks"]]
                bot_names = [n for n in names if n not in ("P1", "P2")]
                dup_ok = len(bot_names) == bots and len(set(bot_names)) == bots
                print("  players in the next round (tick %d): %s" %
                      (last[0]["tick"], names))
            where = locations(run.ds_text()[cut:])
            print("  in the next round: bots on P1 %s" %
                  sorted(b for b, h in where.items() if h == "P1"))
        results.append(("round", bool(ok and all_back and ok2 and dup_ok)))
    finally:
        run.quit_ds()

    want = 6
    if case == "all":
        print()
        results.append(("optout", run_optout(build_dir, out_dir / "optout",
                                             port + 1, bots, slots, ds_exe,
                                             hl_exe, mapdir)))
        want = 7

    print()
    allok = True
    for name, ok in results:
        print("%s: %s" % ("PASS" if ok else "FAIL", name))
        allok = allok and ok
    print("logs: %s" % out_dir)
    return 0 if allok and len(results) == want else 1


