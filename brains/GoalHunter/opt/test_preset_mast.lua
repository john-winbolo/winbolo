do
  local n, bad_name, bad_type, same = 0, {}, {}, {}
  for _, k in ipairs(sorted_keys(MAST)) do
    n = n + 1
    local cur, v = C[k], MAST[k]
    if cur == nil then bad_name[#bad_name + 1] = k
    elseif type(cur) ~= type(v) or type(v) == "table" or type(v) == "function" then
      bad_type[#bad_type + 1] = k
    elseif cur == v then same[#same + 1] = k end
  end
  check("PRESETS.mast has entries", n > 0, n)
  check("every entry names a constant of today", #bad_name == 0, table.concat(bad_name, " "))
  check("every entry is a plain value of the constant's type", #bad_type == 0,
        table.concat(bad_type, " "))
  check("no entry equals today's default", #same == 0, table.concat(same, " "))
end

