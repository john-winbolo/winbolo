    local ok, err = pcall(chunk)
    rawset(_G, "BRAIN_INIT", saved_init)
    rawset(_G, "BRAIN_INIT_ARG", saved_arg)
    return freshC, (not ok and err == STOP)
  end

  local fc, reached = new_brain("preset=mast")
  check("preset=mast: the parse ran", reached, tostring(reached))
  local wrong = {}
  for _, k in ipairs(sorted_keys(MAST)) do
    if fc[k] ~= MAST[k] then
      wrong[#wrong + 1] = string.format("%s=%s", k, tostring(fc[k]))
    end
  end
  check("preset=mast: every PRESETS.mast value is set", #wrong == 0, table.concat(wrong, " "))
  local diff = {}
  for _, k in ipairs(sorted_keys(R221)) do
    local cur = fc[k]
    if cur ~= nil and type(cur) ~= "table" and cur ~= R221[k] then diff[#diff + 1] = k end
  end
  check("preset=mast: every 2.2.1 knob is at its 2.2.1 default", #diff == 0, table.concat(diff, " "))
  check("preset=mast: a knob not in the preset keeps today's default",
        fc.GOAL_REPLAN_INTERVAL == C.GOAL_REPLAN_INTERVAL, tostring(fc.GOAL_REPLAN_INTERVAL))

  fc, reached = new_brain("cfg=FOCUS_SPIKE_ENABLED=true;preset=mast")
  check("cfg= beats preset=mast whatever the order",
        reached and fc.FOCUS_SPIKE_ENABLED == true and fc.LGM_KILL_IMPROVED == false,
        tostring(fc.FOCUS_SPIKE_ENABLED))

  local touched = {}
  for _, k in ipairs(sorted_keys(MAST)) do
    if C[k] ~= shared_before[k] then touched[#touched + 1] = k end
  end
  check("the shared constants were not touched by the fresh brains", #touched == 0,
        table.concat(touched, " "))
end

